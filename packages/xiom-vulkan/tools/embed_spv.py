#!/usr/bin/env python3
"""Embed SPIR-V binaries as C include arrays (xiom.vulkan, shader provenance).

Usage: python tools/embed_spv.py <array_name> <input.spv> <output.inc>

Emits:  static const unsigned int <array_name>[] = { 0x..., ... };
        #define <ARRAY_NAME>_WORDS <count>

The .spv and its GLSL source stay committed next to the .inc so the artifact
is regenerable: glslc <shader> -o <shader>.spv && python tools/embed_spv.py ...
Deterministic: identical input -> identical output.
"""
import sys


def main() -> int:
    if len(sys.argv) != 4:
        print("usage: embed_spv.py <array_name> <input.spv> <output.inc>", file=sys.stderr)
        return 2
    name, src, dst = sys.argv[1], sys.argv[2], sys.argv[3]
    data = open(src, "rb").read()
    if len(data) % 4 != 0:
        print("SPIR-V size is not a multiple of 4", file=sys.stderr)
        return 1
    words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
    lines = [
        "/* Generated by tools/embed_spv.py -- do not edit by hand. */",
        f"/* Source: {src}; {len(data)} bytes, {len(words)} words. */",
        f"static const unsigned int {name}[] = {{",
    ]
    for i in range(0, len(words), 8):
        chunk = ", ".join(f"0x{w:08x}u" for w in words[i:i + 8])
        lines.append("  " + chunk + ",")
    lines.append("};")
    lines.append(f"#define {name.upper()}_WORDS {len(words)}")
    lines.append("")
    with open(dst, "w", newline="\n") as out:
        out.write("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
