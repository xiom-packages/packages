#!/usr/bin/env python3
"""Emit src/struct_meta_*.xi constants from the compiled offset-dumper output.

Input: the struct_dump.exe stdout captured to a text file (SIZE/OFF lines).
Pipeline: tools/gen_vk.py --emit-dump -> find_unavailable_structs.py (converge)
-> struct_dump.exe > dump.txt -> this script.

Run: python packages/xiom-vulkan/tools/gen_struct_meta.py <dump.txt>
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src")
DOCS = os.path.join(ROOT, "docs")


def upper(name):
    s = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name)
    s = re.sub(r"(?<=[A-Z])(?=[A-Z][a-z])", "_", s)
    return re.sub(r"__+", "_", s).upper()


def main():
    if len(sys.argv) < 2:
        print("usage: gen_struct_meta.py <dump.txt>")
        return 1
    dump = sys.argv[1]
    sizes, offs = [], []
    for line in open(dump, encoding="utf-8"):
        p = line.split()
        if not p:
            continue
        if p[0] == "SIZE" and len(p) == 3:
            sizes.append((p[1], int(p[2])))
        elif p[0] == "OFF" and len(p) == 4:
            offs.append((p[1], p[2], int(p[3])))

    consts = []
    names = set()
    collisions = []
    duplicates = []

    def add(c, n):
        if c in names:
            duplicates.append(c)
            return
        names.add(c)
        consts.append((c, n))

    for nm, n in sizes:
        add("VK_SIZEOF_" + upper(nm), n)
    for s, m, n in offs:
        add("VK_OFF_" + upper(s) + "_" + upper(m), n)

    per = 450
    chunks = [consts[i:i + per] for i in range(0, len(consts), per)] or [[]]
    files = []
    for i, chunk in enumerate(chunks, 1):
        lines = ["// GENERATED by tools/gen_struct_meta.py -- do not edit.",
                 "module xiom.vulkan.struct_meta_%d" % i, ""]
        for name, val in chunk:
            lines.append("pub const %s: Int = %d;" % (name, val))
        path = os.path.join(SRC, "struct_meta_%d.xi" % i)
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write("\n".join(lines) + "\n")
        files.append("struct_meta_%d" % i)

    side_path = os.path.join(ROOT, "tools", "struct_dump_skips_full.json")
    side = {}
    if os.path.exists(side_path):
        side = json.load(open(side_path, encoding="utf-8"))

    manifest = {
        "structs_dumped": len(sizes),
        "member_offsets": len(offs),
        "constants": len(consts),
        "files": len(chunks),
        "module_names": files,
        "name_collisions": collisions,
        "duplicates_dropped": duplicates,
        "unavailable_structs": side.get("unavailable_structs", []),
        "sc_api_structs": side.get("sc_api_structs", []),
        "bitfield_members": side.get("bitfield_members", []),
    }
    os.makedirs(DOCS, exist_ok=True)
    with open(os.path.join(DOCS, "struct_meta_manifest.json"), "w",
              encoding="utf-8") as fh:
        json.dump(manifest, fh, indent=2)
    print("struct meta: %d sizes + %d offsets = %d consts in %d files; collisions=%d; "
          "duplicates=%d; unavailable=%d; sc=%d; bitfields=%d"
          % (len(sizes), len(offs), len(consts), len(chunks), len(collisions),
             len(duplicates), len(manifest["unavailable_structs"]),
             len(manifest["sc_api_structs"]), len(manifest["bitfield_members"])))
    return 0


if __name__ == "__main__":
    sys.exit(main())
