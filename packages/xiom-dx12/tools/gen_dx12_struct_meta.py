#!/usr/bin/env python3
"""Emit src/struct_meta_*.xi constants from the compiled struct-dump output.

Pipeline: tools/gen_dx12.py --emit-dump -> compile tools/struct_dump.cpp
with clang against the pinned headers (see docs/COVERAGE.md) -> run to
docs/struct_dump.txt -> this script.

Naming (D3D12_/DXGI_ prefix stripped):
  SIZE D3D12_RESOURCE_DESC 56  ->  pub const D3D12_SIZEOF_RESOURCE_DESC: Int = 56;
  OFF  D3D12_RESOURCE_DESC Width 16
                               ->  pub const D3D12_OFF_RESOURCE_DESC_WIDTH: Int = 16;
  SIZE DXGI_SAMPLE_DESC 8      ->  pub const DXGI_SIZEOF_SAMPLE_DESC: Int = 8;

Run: python packages/xiom-dx12/tools/gen_dx12_struct_meta.py <dump.txt>
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src")
DOCS = os.path.join(ROOT, "docs")


def upper(name):
    s = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name)
    s = re.sub(r"(?<=[A-Z])(?=[A-Z][a-z])", "_", s)
    return re.sub(r"__+", "_", s).upper()


def family(name):
    """D3D12_/DXGI_ prefix stripped; None when unknown."""
    for p in ("D3D12_", "DXGI_"):
        if name.startswith(p):
            return p[:-1], name[len(p):]
    return None, None


def main():
    if len(sys.argv) < 2:
        print("usage: gen_dx12_struct_meta.py <dump.txt>")
        return 1
    dump = sys.argv[1]
    sizes, offs = [], []
    for line in open(dump, encoding="utf-8"):
        p = line.split()
        if not p:
            continue
        if p[0] == "SIZE" and len(p) == 3:
            sizes.append((p[1], int(p[2])))
        elif p[0] == "OFF" and len(p) == 4:
            offs.append((p[1], p[2], int(p[3])))

    consts = []
    names = set()
    duplicates = []
    unknown = []

    def add(c, n):
        if c in names:
            duplicates.append(c)
            return
        names.add(c)
        consts.append((c, n))

    for nm, n in sizes:
        fam, short = family(nm)
        if fam is None:
            unknown.append(nm)
            continue
        add(fam + "_SIZEOF_" + upper(short), n)
    for s, m, n in offs:
        fam, short = family(s)
        if fam is None:
            unknown.append("%s.%s" % (s, m))
            continue
        add(fam + "_OFF_" + upper(short) + "_" + upper(m), n)

    per = 450
    chunks = [consts[i:i + per] for i in range(0, len(consts), per)] or [[]]
    files = []
    for i, chunk in enumerate(chunks, 1):
        lines = ["// GENERATED by tools/gen_dx12_struct_meta.py -- do not edit.",
                 "module xiom.dx12.struct_meta_%d" % i, ""]
        for name, val in chunk:
            lines.append("pub const %s: Int = %d;" % (name, val))
        path = os.path.join(SRC, "struct_meta_%d.xi" % i)
        with open(path, "w", encoding="ascii", newline="\n") as fh:
            fh.write("\n".join(lines) + "\n")
        files.append("struct_meta_%d" % i)

    manifest = {
        "structs_dumped": len(sizes),
        "member_offsets": len(offs),
        "constants": len(consts),
        "files": len(chunks),
        "module_names": files,
        "duplicates_dropped": duplicates,
        "unknown_family": unknown,
    }
    gen_path = os.path.join(DOCS, "gen_manifest.json")
    if os.path.exists(gen_path):
        gen = json.load(open(gen_path, encoding="utf-8"))
        manifest["struct_skips"] = gen.get("struct_skips", [])
    os.makedirs(DOCS, exist_ok=True)
    with open(os.path.join(DOCS, "struct_meta_manifest.json"), "w",
              encoding="utf-8") as fh:
        json.dump(manifest, fh, indent=2)
    print("struct meta: %d sizes + %d offsets = %d consts in %d files; "
          "duplicates=%d unknown=%d"
          % (len(sizes), len(offs), len(consts), len(chunks),
             len(duplicates), len(unknown)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
