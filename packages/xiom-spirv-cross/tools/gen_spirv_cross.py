def frag_header(out, family):
    out.append("// ---------------------------------------------------------------------")
    out.append("// fragment: %s family (%s)" % (family, GEN_TAG))
    out.append("// ---------------------------------------------------------------------")
    out.append("")


def combine(pkg):
    """Concatenate tools/gen/*.xifrag (name order) into spirv_cross.xi.

    The package compiles as a SINGLE XIOM module: the v0.64.3 compiler slot
    has broken cross-module bare-name resolution (the lane's xiom.durable /
    xiom.grpc multi-module packages no longer compile on it), and a `src/`
    directory beside a root module breaks even qualified imports.  The
    fragments keep every reviewable unit far below 600 lines.
    """
    frag_dir = os.path.join(pkg, FRAGMENT_DIR)
    names = sorted(n for n in os.listdir(frag_dir) if n.endswith(".xifrag"))
    lines = []
    lines.append("// xiom.spirv.cross -- SPIRV-Cross bindings (dynamic loader).")
    lines.append("// " + GEN_TAG)
    lines.append("// ASSEMBLED FILE: do not edit; edit tools/gen/*.xifrag + rerun")
    lines.append("// tools/gen_spirv_cross.py (or tools/embed_spv_xiom.py).")
    lines.append("//")
    lines.append("// 100%% of the spirv_cross_c.h C API: the full spvc_* symbol table,")
    lines.append("// a typed wrapper per function, every enum member + macro as a")
    lines.append("// constant, and a resolved=N/N oracle probe.  The package never")
    lines.append("// links against the SDK: spirv-cross-c-shared.dll is resolved at")
    lines.append("// runtime (xiom.ffi.dl); absent DLL = SKIP-green.")
    lines.append("")
    for name in names:
        with io.open(os.path.join(frag_dir, name), encoding="utf-8") as fh:
            lines.extend(fh.read().rstrip("\n").split("\n"))
        lines.append("")
        lines.append("")
    write(os.path.join(pkg, "spirv_cross.xi"), lines)
    return names


def generate(header_path, pkg):
    raw = strip_comments(io.open(header_path, encoding="utf-8").read())
    macros, make_msl = parse_macros(raw)
    text = re.sub(r"\s+", " ", strip_preprocessor(raw))

    typedef_aliases = parse_typedefs(text)
    enums, typedef_kind = parse_enums(text)

    env = {}
    for name, body in macros:
        try:
            env[name] = c_eval(body, env)
        except ValueError:
            continue
    env.setdefault("SPVC_TRUE", 1)
    env.setdefault("SPVC_FALSE", 0)
    enum_values, enums = eval_enum_values(enums, env)

    structs, compute = parse_structs(text, typedef_aliases, typedef_kind)
    for sname in structs:
        compute(sname, set())

    funcs = parse_functions(text)
    for f in funcs:
        f["family"] = assign_family(f["name"])

    counts = {}
    for f in funcs:
        counts[f["family"]] = counts.get(f["family"], 0) + 1
    assert len(funcs) == len(set(f["name"] for f in funcs))
    assert [f for f in FAMILY_ORDER if f not in counts] == []
    assert sum(counts.values()) == len(funcs)

    frag_dir = os.path.join(pkg, FRAGMENT_DIR)
    for d in (pkg, frag_dir):
        if not os.path.isdir(d):
            os.makedirs(d)

    # ---------------- 00_prelude.xifrag (module identity + symbol table) ----
    out = []
    out.append("// " + GEN_TAG)
    out.append("// Source of truth: Include/spirv_cross/spirv_cross_c.h")
    out.append("// (Vulkan SDK 1.4.350.0; SPVC_C_API_VERSION 0.68.0).")
    out.append("")
    out.append("module xiom.spirv.cross")
    out.append("")
    out.append("use xiom.ffi.dl;")
    out.append("")
    out.append("/// Runtime library name (Windows soname).")
    out.append('pub const SPVC_SONAME: Str = "spirv-cross-c-shared.dll";')
    out.append("")
    out.append("/// Load-failure classification: DLL absent vs ABI mismatch.")
    out.append("pub const SPVC_LOAD_ABSENT: Int = 0;")
    out.append("pub const SPVC_LOAD_ABI: Int = 1;")
    out.append("")
    out.append("pub type SpvcLoadError = {")
    out.append("  kind: Int;")
    out.append("  message: Str;")
    out.append("}")
    out.append("")
    out.append("/// A loaded spirv-cross library: `handle` is the dl handle; each")
    out.append("/// `p_*` field is a resolved symbol address.")
    out.append("pub type SpvcLibrary = {")
    out.append("  handle: Int;")
    for f in funcs:
        out.append("  p_%s: Int;" % f["name"])
    out.append("}")
    out.append("")
    out.append("/// Whether the DLL can be loaded on this machine (SKIP gate).")
    out.append("/// Complexity: O(1).")
    out.append("pub fn spirv_cross_present() -> Bool")
    out.append("  requires: true")
    out.append("{")
    out.append("  let h = dl.dl_open(SPVC_SONAME);")
    out.append("  if !h.is_ok { return false; }")
    out.append("  var ig = dl.dl_close(h.value);")
    out.append("  return true;")
    out.append("}")
    out.append("")
    out.append(SLOT_HELPERS)
    write(os.path.join(frag_dir, "00_prelude.xifrag"), out)

    # ---------------- 01_constants.xifrag ------------------------------------
    out = []
    out.append("// " + GEN_TAG)
    out.append("// Every spvc enum member and SPVC_ macro value, plus x64 sizes.")
    out.append("")
    out.append("// ---- SPVC_C_API_VERSION_* ----")
    for name in sorted(n for n in env if n.startswith("SPVC_C_API_VERSION_")):
        out.append("pub const %s: Int = %d;" % (name, env[name]))
    out.append("")
    emitted = set()
    for ename, aliases, members in enums:
        out.append("// ---- enum %s%s ----"
                   % (ename, (" (aka " + ", ".join(aliases) + ")") if aliases else ""))
        for mname, val, _expr in members:
            if mname in emitted:
                continue
            emitted.add(mname)
            out.append("pub const %s: Int = %d;" % (mname, val))
        out.append("")
    out.append("// ---- SPVC_ macros ----")
    for name, _body in macros:
        if name.startswith("SPVC_C_API_VERSION_"):
            continue
        val = env.get(name)
        if val is None:
            continue
        out.append("pub const %s: Int = %d;" % (name, val))
    out.append("")
    out.append("// ---- struct sizes (x64 C layout; out-slot contracts) ----")
    for sname in sorted(structs):
        out.append("pub const SPVC_SIZEOF_%s: Int = %d;"
                   % (sname.upper(), structs[sname]["size"]))
    out.append("")
    out.append("/// SPVC_MAKE_MSL_VERSION(major, minor, patch) -- header macro.")
    out.append("/// Complexity: O(1).")
    out.append("pub fn spvc_make_msl_version(major: Int, minor: Int, patch: Int) -> Int {")
    out.append("  return (major * 10000) + (minor * 100) + (patch);")
    out.append("}")
    out.append("")
    write(os.path.join(frag_dir, "01_constants.xifrag"), out)

    # ---------------- 02_loader.xifrag (resolver + lifecycle) ----------------
    out = []
    out.append("// " + GEN_TAG)
    out.append("// Loads spirv-cross-c-shared.dll and resolves every spvc_* function")
    out.append("// declared in spirv_cross_c.h into the SpvcLibrary symbol table.")
    out.append("")
    out.append("/// Load spirv-cross-c-shared.dll and resolve the full spvc_* symbol")
    out.append("/// table.  Err(SPVC_LOAD_ABSENT) when the DLL is not on PATH;")
    out.append("/// Err(SPVC_LOAD_ABI) when it loads but a symbol is missing (the")
    out.append("/// handle is closed on failure; nothing leaks).")
    out.append("/// Complexity: O(symbols).")
    out.append("pub fn spirv_cross_load() -> Result[SpvcLibrary, SpvcLoadError]")
    out.append("  requires: true")
    out.append("{")
    out.append("  let h = dl.dl_open(SPVC_SONAME);")
    out.append("  if !h.is_ok {")
    out.append("    return Err(SpvcLoadError{ kind: SPVC_LOAD_ABSENT; message: h.error });")
    out.append("  }")
    out.append("  let handle: Int = h.value;")
    out.append("")
    for i, f in enumerate(funcs, start=1):
        out.append('  let a%d = dl.dl_sym(handle, "%s");' % (i, f["name"]))
        out.append('  if !a%d.is_ok { var ig = dl.dl_close(handle); '
                   'return Err(SpvcLoadError{ kind: SPVC_LOAD_ABI; message: "%s" }); }'
                   % (i, f["name"]))
    out.append("")
    out.append("  return Ok(SpvcLibrary{")
    out.append("    handle: handle,")
    for i, f in enumerate(funcs, start=1):
        out.append("    p_%s: a%d.value," % (f["name"], i))
    out.append("  });")
    out.append("}")
    out.append("")
    out.append("/// Close a loaded library.")
    out.append("/// Complexity: O(1).")
    out.append("pub fn spirv_cross_close(lib: &SpvcLibrary)")
    out.append("  requires: lib.handle != 0")
    out.append("{")
    out.append("  var ig = dl.dl_close(lib.handle);")
    out.append("}")
    out.append("")
    write(os.path.join(frag_dir, "02_loader.xifrag"), out)

    # ---------------- 03_oracle.xifrag (resolved=N/N probe) ------------------
    out = []
    out.append("// " + GEN_TAG)
    out.append("// Runtime resolution probe: resolves EVERY oracle function name")
    out.append("// (the full header-declared set) and returns the resolved count.")
    out.append("")
    out.append("/// Oracle N: every SPVC_PUBLIC_API function in spirv_cross_c.h.")
    out.append("pub const SPVC_ORACLE_COUNT: Int = %d;" % len(funcs))
    out.append("")
    out.append("fn spvc_sym_ok(handle: Int, name: Str) -> Int")
    out.append("  requires: handle != 0")
    out.append("{")
    out.append("  let r = dl.dl_sym(handle, name);")
    out.append("  if r.is_ok { return 1; }")
    out.append("  return 0;")
    out.append("}")
    out.append("")
    out.append("/// Resolve every oracle name against the real DLL; returns N")
    out.append("/// (== SPVC_ORACLE_COUNT when the DLL exports the full header set).")
    out.append("/// Returns 0 when the DLL is absent (caller reports SKIP).")
    out.append("/// Complexity: O(symbols).")
    out.append("pub fn spvc_probe_resolution() -> Int")
    out.append("  requires: true")
    out.append("{")
    out.append("  let h = dl.dl_open(SPVC_SONAME);")
    out.append("  if !h.is_ok { return 0; }")
    out.append("  let handle: Int = h.value;")
    out.append("  var n: Int = 0;")
    for f in funcs:
        out.append('  n = n + spvc_sym_ok(handle, "%s");' % f["name"])
    out.append("  var ig = dl.dl_close(handle);")
    out.append("  return n;")
    out.append("}")
    out.append("")
    write(os.path.join(frag_dir, "03_oracle.xifrag"), out)

    # ---------------- family fragments (10_..19_) ----------------------------
    for idx, family in enumerate(FAMILY_ORDER):
        fam_funcs = [f for f in funcs if f["family"] == family]
        out = []
        frag_header(out, family)
        for f in fam_funcs:
            if f["name"] == "spvc_context_set_error_callback":
                out.append(ERROR_CALLBACK_WRAPPER)
                continue
            out.append(gen_wrapper(f, structs, typedef_kind))
            out.append("")
        if family == "compiler":
            out.append(COMPILE_STRING_HELPER)
        write(os.path.join(frag_dir, "%02d_%s.xifrag" % (10 + idx, family)), out)

    names = combine(pkg)
    return {"functions": len(funcs), "families": counts,
            "constants": len(emitted) + sum(1 for n, _b in macros
                                            if env.get(n) is not None
                                            and not n.startswith("SPVC_C_API_VERSION_")),
            "enum_members": len(emitted), "enums": len(enums),
            "structs": len(structs), "macros": len(macros),
            "fragments": names,
            "struct_sizes": {s: structs[s]["size"] for s in sorted(structs)}}


SLOT_HELPERS = """/// A zeroed XIOM-owned out-param slot of `n` bytes (one owned slot per
/// out-param; no malloc/free, no raw pointer arithmetic).
/// Complexity: O(n).
pub fn spvc_slot(n: Int) -> Vec[UInt8]
  requires: n > 0
{
  var s: Vec[UInt8] = Vec[UInt8].new();
  var i: Int = 0;
  while i < n {
    s.push(0 as UInt8);
    i = i + 1;
  }
  return s;
}

/// Little-endian u32 read from an owned slot (byte-indexed).
/// Complexity: O(1).
pub fn spvc_read_u32_at(buf: &Vec[UInt8], off: Int) -> Int
  requires: off >= 0
  requires: buf.len() >= off + 4
{
  let b0 = buf[off + 0] as Int;
  let b1 = buf[off + 1] as Int;
  let b2 = buf[off + 2] as Int;
  let b3 = buf[off + 3] as Int;
  return b0 | (b1 << 8) | (b2 << 16) | (b3 << 24);
}

/// Signed i32 read from an owned slot.
/// Complexity: O(1).
pub fn spvc_read_i32_at(buf: &Vec[UInt8], off: Int) -> Int
  requires: off >= 0
  requires: buf.len() >= off + 4
{
  let u = spvc_read_u32_at(buf, off);
  if u >= 0x80000000 { return u - 0x100000000; }
  return u;
}

/// Little-endian u64 read from an owned slot (pointer/count out-params).
/// Complexity: O(1).
pub fn spvc_read_u64_at(buf: &Vec[UInt8], off: Int) -> Int
  requires: off >= 0
  requires: buf.len() >= off + 8
{
  let lo = spvc_read_u32_at(buf, off);
  let hi = spvc_read_u32_at(buf, off + 4);
  return lo | (hi << 32);
}

/// Byte-indexed little-endian u32 write into an owned slot.
/// Complexity: O(1).
pub fn spvc_write_u32_le(buf: &mut Vec[UInt8], off: Int, v: Int)
  requires: off >= 0
  requires: buf.len() >= off + 4
{
  buf[off + 0] = (v & 0xFF) as UInt8;
  buf[off + 1] = ((v >> 8) & 0xFF) as UInt8;
  buf[off + 2] = ((v >> 16) & 0xFF) as UInt8;
  buf[off + 3] = ((v >> 24) & 0xFF) as UInt8;
}

/// Byte-indexed little-endian u64 write into an owned slot.
/// Complexity: O(1).
pub fn spvc_write_u64_le(buf: &mut Vec[UInt8], off: Int, v: Int)
  requires: off >= 0
  requires: buf.len() >= off + 8
{
  spvc_write_u32_le(buf, off + 0, v & 0xFFFFFFFF);
  spvc_write_u32_le(buf, off + 4, (v >> 32) & 0xFFFFFFFF);
}
"""

ERROR_CALLBACK_WRAPPER = """// -------------------------------------------------------------------------
// Special case: spvc_context_set_error_callback takes a C function pointer.
// A fixed dispatcher is registered; the ergonomic handler is 1-arg and the
// last registered handler wins (Vec[fn] element calls with >= 2 args are a
// known compiler hazard, B-15, so the handler takes only the message).
// -------------------------------------------------------------------------

var spvc_error_handlers: Vec[fn(Str) -> Unit] = Vec[fn(Str) -> Unit].new();

fn spvc_error_dispatch(userdata: Int, error: Int) {
  var ig = userdata;
  if error == 0 { return; }
  if spvc_error_handlers.len() == 0 { return; }
  let h = spvc_error_handlers[spvc_error_handlers.len() - 1];
  unsafe {
    h(Str::from_c_str(error as *UInt8));
  }
}

/// `void spvc_context_set_error_callback(spvc_context context, spvc_error_callback cb, void *userdata)`
/// -- generated special case; registers the fixed dispatcher.
/// Complexity: O(1).
pub fn spvc_context_set_error_callback(lib: &SpvcLibrary, context: Int, cb: fn(Str) -> Unit, userdata: Int)
  requires: lib.handle != 0
  requires: context != 0
{
  spvc_error_handlers.push(cb);
  unsafe {
    let f = lib.p_spvc_context_set_error_callback as fn(Int, fn(Int, Int) -> Unit, Int);
    f(context, spvc_error_dispatch, userdata);
  }
}
"""

COMPILE_STRING_HELPER = """/// Compile the active entry point to a string ("" on failure; the returned
/// string is owned by the spvc context -- this helper copies it).
/// Complexity: O(output).
pub fn spvc_compiler_compile_string(lib: &SpvcLibrary, compiler: Int) -> Str
  requires: lib.handle != 0
  requires: compiler != 0
{
  var src: Vec[UInt8] = spvc_slot(8);
  let rc = spvc_compiler_compile(lib, compiler, &mut src);
  if rc != 0 { return ""; }
  let p = spvc_read_u64_at(&src, 0);
  if p == 0 { return ""; }
  unsafe {
    return Str::from_c_str(p as *UInt8);
  }
}
"""


def write(path, lines):
    with io.open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--header", default=DEFAULT_HEADER)
    ap.add_argument("--out", default=os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    if args.check:
        raw = strip_comments(io.open(args.header, encoding="utf-8").read())
        macros, _ = parse_macros(raw)
        text = re.sub(r"\s+", " ", strip_preprocessor(raw))
        enums, typedef_kind = parse_enums(text)
        typedef_aliases = parse_typedefs(text)
        structs, compute = parse_structs(text, typedef_aliases, typedef_kind)
        for s in structs:
            compute(s, set())
        funcs = parse_functions(text)
        counts = {}
        for f in funcs:
            fam = assign_family(f["name"])
            counts[fam] = counts.get(fam, 0) + 1
