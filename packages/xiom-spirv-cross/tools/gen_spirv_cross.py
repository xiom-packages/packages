#!/usr/bin/env python3
"""Generate the xiom.spirv.cross XIOM binding modules from spirv_cross_c.h.

Oracle: the installed Khronos Vulkan SDK header
`Include/spirv_cross/spirv_cross_c.h` (SDK 1.4.350.0, SPVC_C_API_VERSION
0.68.0).  The generator parses the real C declarations and emits:

  * spirv_cross.xi               -- loader entry (soname, error type, the
                                   169-entry symbol table + dl_sym resolver)
  * src/spvc_slot.xi             -- owned-slot helpers (B-11..B-20 idioms)
  * src/spvc_constants.xi        -- every spvc enum member + SPVC_ macro,
                                   struct sizeof constants, MSL version math
  * src/spvc_oracle.xi           -- `resolved=N/N` runtime probe
  * src/spvc_<family>.xi         -- typed wrapper per C function, split by
                                   header section: context / compiler / glsl /
                                   hlsl / msl / resources / type / constant /
                                   buffer / reflect

Usage:
  python tools/gen_spirv_cross.py --check
  python tools/gen_spirv_cross.py [--header <path>] [--out <package-dir>]

Deterministic: identical header bytes -> identical output.  Generated files
carry a provenance header; do not edit them by hand.
"""

