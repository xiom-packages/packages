def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    text = re.sub(r"//[^\n]*", " ", text)
    return text


def strip_preprocessor(text):
    """Drop preprocessor lines (macros are parsed separately, from raw)."""
    return re.sub(r"^[ \t]*#[^\n]*$", " ", text, flags=re.M)


def norm(t):
    return re.sub(r"\s+", " ", t).strip()


def norm_type(t):
    """Normalize a C type spelling: 'const char *' -> 'const char*'."""
    t = norm(t)
    t = re.sub(r"\s*\*\s*", "*", t)
    return t


def parse_typedefs(text):
    """Simple typedefs: `typedef unsigned spvc_hlsl_binding_flags;`."""
    out = {}
    for m in re.finditer(
            r"typedef\s+([A-Za-z_][A-Za-z0-9_ ]*?)\s+([A-Za-z_][A-Za-z0-9_]*)\s*;", text):
        base, name = norm(m.group(1)), m.group(2)
        if base.startswith("struct") or base.startswith("enum"):
            continue
        out[name] = base
    return out


def parse_enums(text):
    """Ordered enums: [(name, [aliases], [(member, expr)])] + typedef kinds."""
    enums = []
    typedef_kind = {}
    for m in re.finditer(
            r"typedef\s+enum\s+([A-Za-z_][A-Za-z0-9_]*)\s*\{(.*?)\}\s*([^;]*);",
            text, flags=re.S):
        name, body, alias_blob = m.group(1), m.group(2), m.group(3)
        aliases = [a.strip() for a in alias_blob.split(",") if a.strip()]
        members = []
        for raw in body.split(","):
            raw = norm(raw)
            if not raw:
                continue
            if "=" in raw:
                mname, expr = raw.split("=", 1)
                members.append((mname.strip(), expr.strip()))
            else:
                members.append((raw, None))
        enums.append((name, aliases, members))
        for a in aliases:
            typedef_kind[a] = "enum"
    return enums, typedef_kind


def c_eval(expr, env):
    """Evaluate the C constant-expression subset used by the header."""
    e = expr
    e = re.sub(r"~\(\s*(\d+)\s*[uU]?\s*\)",
               lambda m: str(0xFFFFFFFF - int(m.group(1))), e)
    e = re.sub(r"(?<=[0-9a-fA-F])[uUlL]+\b", "", e)
    try:
        return int(eval(e, {"__builtins__": {}}, dict(env)))  # noqa: S307
    except Exception as exc:  # pragma: no cover - generator diagnostics
        raise ValueError("cannot evaluate %r (env %d names): %s"
                         % (expr, len(env), exc))


def eval_enum_values(enums, env):
    """Return (member_values dict, rewritten enums with triples)."""
    values = {}
    out_enums = []
    for ename, aliases, members in enums:
        nxt = 0
        triples = []
        for mname, expr in members:
            val = nxt if expr is None else c_eval(expr, env)
            values[mname] = val
            env[mname] = val  # same-enum alias references
            triples.append((mname, val, expr))
            nxt = val + 1
        out_enums.append((ename, aliases, triples))
    return values, out_enums


def parse_macros(text):
    """Object-like SPVC_ macros + the function-like MAKE_MSL_VERSION flag."""
    macros = []
    make_msl = False
    for m in re.finditer(
            r"^#define\s+([A-Za-z_][A-Za-z0-9_]*)(\(([^)]*)\))?[ \t]*(.*)$",
            text, flags=re.M):
        name, args, body = m.group(1), m.group(3), norm(m.group(4))
        if name in ("SPVC_PUBLIC_API", "SPVC_EXPORT_SYMBOLS"):
            continue
        if not name.startswith("SPVC_"):
            continue
        if args is not None:
            if name == "SPVC_MAKE_MSL_VERSION":
                make_msl = True
            continue
        body = re.sub(r"\(\((?:spvc_bool|unsigned|int|char\s*\*)\)[ \t]*", "(", body)
        macros.append((name, body))
    return macros, make_msl


MEMBER_KNOWN = (set(C_LAYOUT) | INT_LIKE |
                {"spvc_hlsl_binding_flags", "spvc_msl_vertex_format",
                 "spvc_msl_shader_input_format", "spvc_msl_shader_variable_format"})


def parse_member_names(rest, decl):
    names = []
    for part in rest.split(","):
        part = norm(part)
        mm = re.match(r"^([A-Za-z_][A-Za-z0-9_]*)\s*(\[\s*(\d+)\s*\])?$", part)
        if not mm:
            raise ValueError("unparsed member name %r in %r" % (part, decl))
        names.append((mm.group(1), int(mm.group(3)) if mm.group(3) else 1))
    return names


def parse_member_decl(decl, known_types):
    """Split `TYPE a, b[2]` into (type, [(name, count), ...])."""
    decl = norm(decl)
    pm = re.match(r"^(.*?\*)\s*(.+)$", decl)
    if pm:
        return norm_type(pm.group(1)), parse_member_names(pm.group(2), decl)
    best = None
    for m in re.finditer(r"[A-Za-z_][A-Za-z0-9_]*", decl):
        cand = decl[:m.end()].strip()
        if cand in known_types or (cand.startswith("Spv") and " " not in cand):
            if best is None or len(cand) > len(best):
                best = cand
    if best is None:
        raise ValueError("unknown member type in %r" % decl)
    return best, parse_member_names(decl[len(best):].strip(), decl)


def parse_structs(text, typedef_aliases, typedef_kind):
    """Parse structs and compute x64 C layout sizes."""
    structs = {}
    for m in re.finditer(
            r"typedef\s+struct\s+([A-Za-z_][A-Za-z0-9_]*)\s*\{(.*?)\}\s*([^;]*);",
            text, flags=re.S):
        name, body = m.group(1), m.group(2)
        structs[name] = {"members": [], "size": None, "align": None, "text": body}

    known_types = (set(C_LAYOUT) | set(typedef_aliases) | set(typedef_kind)
                   | set(structs) | MEMBER_KNOWN)

    def layout(t):
        t = norm_type(t)
        if "*" in t:
            return (8, 8)
        if t in C_LAYOUT:
            return C_LAYOUT[t]
        if t in structs:
            info = structs[t]
            if info["size"] is None:
                compute(t, set())
            return (info["size"], info["align"])
        if t in typedef_aliases:
            base = typedef_aliases[t]
            if base in C_LAYOUT:
                return C_LAYOUT[base]
            return (4, 4)  # enum-typed simple typedef default
        if t in typedef_kind:
            return (4, 4)
        if t.startswith("Spv"):
            return (4, 4)
        raise ValueError("unknown member type %r" % t)

    def compute(name, seen):
        if name in seen:
            raise ValueError("struct cycle: %s" % name)
        seen.add(name)
        off, amax = 0, 1
        for decl in structs[name]["text"].split(";"):
            decl = norm(decl)
            if not decl:
                continue
            mtype, names = parse_member_decl(decl, known_types)
            size, align = layout(mtype)
            if off % align != 0:
                off += align - (off % align)
            for _n, count in names:
                off += size * count
            amax = max(amax, align)
        if off % amax != 0:
            off += amax - (off % amax)
        structs[name]["size"] = off
        structs[name]["align"] = amax
        seen.discard(name)

    return structs, compute


def parse_functions(text):
    funcs = []
    for m in re.finditer(
            r"SPVC_PUBLIC_API\s+(.*?)\b(spvc_[A-Za-z0-9_]+)\s*\(([^;]*?)\)\s*;",
            text, flags=re.S):
        ret, name, params = norm(m.group(1)), m.group(2), norm(m.group(3))
        plist = []
        if params and params != "void":
            for raw in params.split(","):
                raw = norm(raw)
                mm = re.match(r"^(.*?)\b([A-Za-z_][A-Za-z0-9_]*)\s*$", raw)
                if not mm:
                    raise ValueError("unparsed param %r in %s" % (raw, name))
                plist.append({"type": norm_type(mm.group(1)), "name": mm.group(2)})
        funcs.append({"ret": norm_type(ret), "name": name, "params": plist})
    return funcs


def base_of(t):
    t = norm_type(t)
    const = t.startswith("const ")
    if const:
        t = t[len("const "):]
    stars = 0
    while t.endswith("*"):
        stars += 1
        t = t[:-1].strip()
    return const, t, stars


def xiom_cast_scalar(t, typedef_kind):
    if t == "spvc_result":
        return "Int32"
    if t == "spvc_bool":
        return "UInt8"
    if t == "size_t":
        return "UInt64"
    if t == "float":
        return "Float32"
    if t == "double":
        return "Float64"
    if t in ID_TYPES or t in ("unsigned", "unsigned int"):
        return "UInt32"
    if t == "spvc_hlsl_binding_flags":
        return "UInt32"
    if t == "unsigned long long":
        return "UInt64"
    if t == "long long":
        return "Int64"
    if t == "unsigned short":
        return "UInt16"
    if t in ("signed short", "short"):
        return "Int16"
    if t == "unsigned char":
        return "UInt8"
    if t in ("signed char", "char"):
        return "Int8"
    if t == "int":
        return "Int32"
    if t in typedef_kind:
        return "Int32"
    if t.startswith("Spv"):
        return "Int32"
    raise ValueError("unmapped scalar type %r" % t)


def slot_size_of(t, structs, typedef_kind):
    if t in SCALAR_SIZES:
        return SCALAR_SIZES[t]
    if t in typedef_kind:
        return 4
    if t.endswith("_flags"):
        return 4
    if t in structs:
        return structs[t]["size"]
    raise ValueError("no size for %r" % t)


def role_of(fn, p, structs, typedef_kind):
    """Classify a parameter: (role, cast_type, slot_bytes_or_None)."""
    t = p["type"]
    const, base, stars = base_of(t)
    if t == "spvc_error_callback":
        return ("callback", "fn(Int, Int) -> Unit", None)
    if stars == 0:
        if base in OPAQUE_TYPES:
            return ("handle", "Int", None)
        return ("scalar", xiom_cast_scalar(base, typedef_kind), None)
    assert stars >= 1
    if base == "char" and stars == 1:
        return ("str", "*UInt8", None)
    if base == "char" and stars >= 2:
        return ("out", "*UInt8", 8)
    if base == "void":
        return ("scalar", "Int", None)
    if base in OPAQUE_TYPES:
        if stars == 1 and const:
            return ("handle", "Int", None)
        return ("out", "*UInt8", 8)
    if stars == 1:
        if base in structs:
            if const:
                return ("in_ptr", "*UInt8", None)
            return ("out", "*UInt8", structs[base]["size"])
        if base in SCALAR_SIZES or base in typedef_kind or base.startswith("Spv"):
            if const:
                return ("in_ptr", "Int", None)
            return ("out", "*UInt8", slot_size_of(base, structs, typedef_kind))
    return ("out", "*UInt8", 8)


def ret_kind(fn, typedef_kind):
    const, base, stars = base_of(fn["ret"])
    if stars > 0:
        if base == "char":
            return ("str", "*UInt8")
        return ("ptr_int", "*UInt8")
    if base == "void":
        return ("unit", None)
    if base == "spvc_bool":
        return ("bool", "UInt8")
    if base == "float":
        return ("float32", "Float32")
    if base == "double":
        return ("float64", "Float64")
    if base == "spvc_result":
        return ("result", "Int32")
    if base in OPAQUE_TYPES:
        return ("ptr_int", "*UInt8")
    return ("int", xiom_cast_scalar(base, typedef_kind))


def sanitize(name):
    return name + "_v" if name in KEYWORDS else name


def gen_wrapper(fn, structs, typedef_kind):
    roles = [role_of(fn, p, structs, typedef_kind) for p in fn["params"]]

    cast_params, call_args, sig_params, requires = [], [], [], ["lib.handle != 0"]
    for (pname, p), (role, cast_t, slot_sz) in zip(
            [(p["name"], p) for p in fn["params"]], roles):
        xiom_name = sanitize(pname)
        if role == "scalar":
            sig_params.append("%s: Int" % xiom_name)
            cast_params.append("Int")  # C x64 ABI: ints cross as Int (sdl3 pattern)
            call_args.append(xiom_name)
        elif role == "handle":
            sig_params.append("%s: Int" % xiom_name)
            cast_params.append("Int")
            call_args.append(xiom_name)
            requires.append("%s != 0" % xiom_name)
        elif role == "str":
            sig_params.append("%s: Str" % xiom_name)
            cast_params.append("*UInt8")
            call_args.append("%s.c_str()" % xiom_name)
        elif role in ("in_ptr", "out"):
            sig_params.append("%s: &mut Vec[UInt8]" % xiom_name)
            cast_params.append("*UInt8")
            call_args.append("%s.as_mut_ptr()" % xiom_name)
            _const, base, _stars = base_of(p["type"])
            if role == "out":
                requires.append("%s.len() >= %d" % (xiom_name, slot_sz))
            elif base in structs or base in ID_TYPES:
                # aggregate input buffer + companion COUNT param (only when
                # the immediately following parameter is a scalar count)
                idx = [q["name"] for q in fn["params"]].index(pname)
                if idx + 1 < len(fn["params"]):
                    pnext = fn["params"][idx + 1]
                    nrole = role_of(fn, pnext, structs, typedef_kind)[0]
                    if nrole == "scalar":
                        nxt = sanitize(pnext["name"])
                        unit = "SPVC_SIZEOF_%s" % base.upper() if base in structs else "4"
                        requires.append("%s.len() >= %s * %s"
                                        % (xiom_name, nxt, unit))
        elif role == "callback":
            sig_params.append("%s: fn(Int, Int) -> Unit" % xiom_name)
            cast_params.append("fn(Int, Int) -> Unit")
            call_args.append("spvc_error_dispatch")
        else:  # pragma: no cover
            raise ValueError("role %r" % role)

    rkind, rcast = ret_kind(fn, typedef_kind)
    lines = []
    c_sig = fmt_c_signature(fn)
    lines.append("/// `%s` -- generated binding (%s family)." % (c_sig, fn["family"]))
    if any(r == "out" for r, _c, _s in roles):
        lines.append("/// Out-params are separate XIOM-owned `&mut Vec[UInt8]` slots")
        lines.append("/// (B-11..B-20: all writes stay on the XIOM-owned side).")
    lines.append("/// Complexity: O(1).")
    ret_sig = {"bool": " -> Bool", "result": " -> Int", "int": " -> Int",
               "ptr_int": " -> Int", "str": " -> Str",
               "float32": " -> Float32", "float64": " -> Float64",
               "unit": ""}[rkind]
    lines.append("pub fn %s(lib: &SpvcLibrary%s)%s"
                 % (fn["name"], "".join(", " + s for s in sig_params), ret_sig))
    for req in requires:
        lines.append("  requires: %s" % req)
    lines.append("{")
    lines.append("  unsafe {")
    cast_ret = {"unit": "", "bool": " -> UInt8", "result": " -> %s" % rcast,
                "int": " -> %s" % rcast, "ptr_int": " -> *UInt8",
                "str": " -> *UInt8", "float32": " -> Float32",
                "float64": " -> Float64"}[rkind]
    lines.append("    let f = lib.p_%s as fn(%s)%s;"
                 % (fn["name"], ", ".join(cast_params), cast_ret))
    call = "f(%s)" % ", ".join(call_args)
    if rkind == "unit":
        lines.append("    %s;" % call)
    elif rkind == "bool":
        lines.append("    return (%s as Int) != 0;" % call)
    elif rkind in ("result", "int"):
        lines.append("    return %s as Int;" % call)
    elif rkind in ("float32", "float64"):
        lines.append("    return %s;" % call)
    elif rkind == "ptr_int":
        lines.append("    let p = %s;" % call)
        lines.append("    return p as Int;")
    elif rkind == "str":
        lines.append("    let p = %s;" % call)
        lines.append('    if (p as Int) == 0 { return ""; }')
        lines.append("    return Str::from_c_str(p);")
    lines.append("  }")
    lines.append("}")
    return "\n".join(lines)


def fmt_c_signature(fn):
    params = ", ".join("%s %s" % (p["type"], p["name"]) for p in fn["params"])
    if base_of(fn["ret"])[1] != "void":
        return "%s %s(%s)" % (fn["ret"], fn["name"], params)
    return "void %s(%s)" % (fn["name"], params)


def assign_family(name):
    n = name
    if n.startswith("spvc_context_") or n in ("spvc_get_version",
                                              "spvc_get_commit_revision_and_timestamp"):
        return "context"
    if "_msl_" in n or n.startswith("spvc_msl_"):
        return "msl"
    if "_hlsl_" in n or n.startswith("spvc_hlsl_"):
        return "hlsl"
    if n.startswith("spvc_resources_") or n in (
            "spvc_compiler_create_shader_resources",
            "spvc_compiler_create_shader_resources_for_active_variables",
            "spvc_compiler_get_active_interface_variables",
            "spvc_compiler_set_enabled_interface_variables"):
        return "resources"
    if n.startswith("spvc_type_") or n == "spvc_compiler_get_type_handle":
        return "type"
    if n.startswith("spvc_constant_") or n in (
            "spvc_compiler_get_constant_handle",
            "spvc_compiler_get_specialization_constants",
            "spvc_compiler_get_work_group_size_specialization_constants"):
        return "constant"
    if ("_buffer_" in n or "_struct_size" in n or "_member_size" in n
            or "_member_offset" in n
            or "_array_stride" in n or "_matrix_stride" in n
            or n == "spvc_compiler_get_active_buffer_ranges") \
            and n != "spvc_compiler_flatten_buffer_block":
        return "buffer"
    if n in ("spvc_compiler_create_compiler_options",
             "spvc_compiler_options_set_bool",
             "spvc_compiler_options_set_uint",
             "spvc_compiler_install_compiler_options",
             "spvc_compiler_add_header_line",
             "spvc_compiler_require_extension",
             "spvc_compiler_get_num_required_extensions",
             "spvc_compiler_get_required_extension"):
        return "glsl"
    if ("_decoration" in n
            or n in ("spvc_compiler_get_name", "spvc_compiler_set_name",
                     "spvc_compiler_get_member_name", "spvc_compiler_set_member_name")
            or n.startswith("spvc_compiler_get_entry_points")
            or n.startswith("spvc_compiler_set_entry_point")
            or n.startswith("spvc_compiler_rename_entry_point")
            or n.startswith("spvc_compiler_get_cleansed_entry_point_name")
            or n.startswith("spvc_compiler_set_execution_mode")
            or n.startswith("spvc_compiler_unset_execution_mode")
            or n.startswith("spvc_compiler_get_execution_mode")
            or n.startswith("spvc_compiler_get_execution_model")
            or n.startswith("spvc_compiler_update_active_builtins")
            or n.startswith("spvc_compiler_has_active_builtin")
            or n.startswith("spvc_compiler_get_declared_")
            or n.startswith("spvc_compiler_get_remapped_declared_block_name")
            or n.startswith("spvc_compiler_build_dummy_sampler")
            or n.startswith("spvc_compiler_build_combined_image_samplers")
            or n.startswith("spvc_compiler_get_combined_image_samplers")):
        return "reflect"
    return "compiler"


