# Generate src/usd_trampolines.cpp from the bridge's undefined USD symbols.
#
# The suite is compiled without an import library for usd_ms.dll.  Every USD
# C++ function the bridge calls is defined here as a local x64 trampoline
# (jmp through a slot).  usdbridge_resolve_all() fills the slots from the
# loaded usd_ms.dll.  This keeps the executable free of a static usd_ms.dll
# import, so it starts (and the suite SKIPs) when the runtime is absent.
#
# Usage:
#   .\tools\gen_trampolines.ps1
#     -Bridge src\usd_bridge.cpp
#     -Dll    E:\repos\usd-core\wheel\pxr\usd_ms.dll
#
# The bridge is compiled at -O0 and -O2; the union of undefined USD symbols
# is used so the generated set is stable across the XIOM optimization level.
param(
    [string]$Bridge = "",
    [string]$Dll = "E:\repos\usd-core\wheel\pxr\usd_ms.dll",
    [string]$Clang = "C:\Program Files\LLVM\bin\clang++.exe",
    [string]$Readobj = "C:\Program Files\LLVM\bin\llvm-readobj.exe",
    [string]$Nm = "C:\Program Files\LLVM\bin\llvm-nm.exe"
)
$ErrorActionPreference = "Stop"
$pkg = Split-Path -Parent $PSScriptRoot
if (-not $Bridge) { $Bridge = Join-Path $pkg "src\usd_bridge.cpp" }
$tmp = Join-Path ([System.IO.Path]::GetTempPath()) ("usd-tramp-" + [guid]::NewGuid().ToString("N"))
New-Item -ItemType Directory -Force -Path $tmp | Out-Null

$exports = & $Readobj --coff-exports $Dll | ForEach-Object { if ($_ -match '^  Name: (.*)$') { $Matches[1] } }
$exportSet = [System.Collections.Generic.HashSet[string]]::new([string[]]$exports)
$union = New-Object System.Collections.Generic.HashSet[string]
foreach ($opt in @("", "-O2")) {
    $obj = Join-Path $tmp ("bridge" + ($opt -replace '-','_') + ".obj")
    $args = @("-std=c++17")
    if ($opt) { $args += $opt }
    $args += @("-c", $Bridge, "-o", $obj)
    & $Clang @args | Out-Null
    $undef = & $Nm --undefined-only $obj | ForEach-Object { if ($_ -match '^\s*U\s+(.+)$') { $Matches[1].Trim() } }
    foreach ($u in $undef) { if ($exportSet.Contains($u)) { [void]$union.Add($u) } }
}
$names = @($union | Sort-Object)
Write-Host "USD function symbols: $($names.Count)"

$out = New-Object System.Collections.Generic.List[string]
$out.Add("// GENERATED by tools/gen_trampolines.ps1 -- do not edit by hand.")
$out.Add("// Local x64 trampolines for the OpenUSD v26.08 functions called by")
$out.Add("// usd_bridge.cpp.  Slots are filled by usdbridge_resolve_all() after")
$out.Add("// usd_ms.dll is loaded; no static usd_ms.dll import exists.")
$out.Add("")
$out.Add("#include <windows.h>")
$out.Add("#include <cstddef>")
$out.Add("")
$out.Add("extern ""C"" {")
for ($i = 0; $i -lt $names.Count; $i++) {
    $out.Add("void *usd_tramp_slot_$i = nullptr;")
}
$out.Add("}")
$out.Add("")
$out.Add("extern ""C"" int usdbridge_resolve_all(void *module) {")
$out.Add("    HMODULE h = reinterpret_cast<HMODULE>(module);")
$out.Add("    struct Entry { const char *name; void **slot; };")
$out.Add("    static const Entry entries[] = {")
for ($i = 0; $i -lt $names.Count; $i++) {
    $escaped = $names[$i] -replace '\\','\\' -replace '"','\"'
    $out.Add("        { ""$escaped"", &usd_tramp_slot_$i },")
}
$out.Add("    };")
$out.Add("    for (size_t i = 0; i < sizeof(entries) / sizeof(entries[0]); ++i) {")
$out.Add("        *entries[i].slot = reinterpret_cast<void *>(GetProcAddress(h, entries[i].name));")
$out.Add("        if (!*entries[i].slot) return 0;")
$out.Add("    }")
$out.Add("    return 1;")
$out.Add("}")
$out.Add("")
$out.Add("asm(")
$out.Add('    ".text\n"')
for ($i = 0; $i -lt $names.Count; $i++) {
    $escaped = $names[$i] -replace '\\','\\' -replace '"','\"'
    $out.Add('    ".globl \"' + $escaped + '\"\n"')
    $out.Add('    "\"' + $escaped + '\":\n"')
    $out.Add('    "  jmp *usd_tramp_slot_' + $i + '(%rip)\n"')
}
$out.Add('    "  .att_syntax prefix\n"')
$out.Add(");")
$out.Add("")
$outPath = Join-Path $pkg "src\usd_trampolines.cpp"
[System.IO.File]::WriteAllLines($outPath, $out, (New-Object System.Text.UTF8Encoding($false)))
Write-Host "wrote $outPath"
Remove-Item -LiteralPath $tmp -Recurse -Force -ErrorAction SilentlyContinue
