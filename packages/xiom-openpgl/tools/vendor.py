#!/usr/bin/env python3
# ============================================================================
# xiom.openpgl vendoring generator.
# ============================================================================
# Mirrors the pinned upstream trees into `vendor/openpgl/` with exactly two
# kinds of textual transform, and emits one TU wrapper per compiled source
# (the xiom link line has no -I passthrough: quoted includes resolve through
# the compiler's include stack, so the tree is flattened at the wrapper root):
#
#   T1 include rewrite (mechanical, counted):
#        #include <embreeSrc/...>            -> "third-party/embreeSrc/..."
#        #include <tbb/...>                   -> "tbb/..." (quoted)
#        #include <nanoflann/include/...>   -> "third-party/nanoflann/include/..."
#   T2 portability gates (two literal replacements, asserted exactly-once):
#        oneapi/tbb/detail/_config.h :: __TBB_TSX_INTRINSICS_PRESENT
#        src/tbb/scheduler_common.h  :: waitpkg _tpause gate
#        Reason: clang >= 20 requires the rtm/waitpkg target features for those
#        MSVC-visible intrinsics; the xiom link line passes no -m flags.  With
#        the gates off TBB takes its documented non-TSX / non-WAITPKG fallbacks.
#
# Generated (not upstream): include/openpgl/defines.h, include/openpgl/version.h
# (upstream ships these as CMake configure_file templates: defines.h.in,
# version.h.in; the port bakes the same all-optional-features-off defaults).
#
# Usage:
#   python tools/vendor.py --openpgl E:\repos\openpgl --tbb E:\repos\oneTBB
# Exit code: 0 = vendor tree regenerated and self-checked, 1 = error.
# ============================================================================
# Copyright (c) 2026 Eleftherios Notas and The XIOM Authors
# SPDX-License-Identifier: MIT OR Apache-2.0

import argparse
import hashlib
import os
import re
import shutil
import sys

PGL_PIN = "5c50cd7a331647a69e28cc8a19ff204039cbe78d"   # tag v0.7.1
TBB_PIN = "1c4c93fc5398c4a1acb3492c02db4699f3048dea"   # tag v2021.13.0

WRAPPER_HEADER = "// GENERATED by tools/vendor.py -- do not edit by hand."

PGL_DEFINES = """\
// GENERATED by tools/vendor.py (upstream include/openpgl/defines.h.in).
// All optional features intentionally off:
// OPENPGL_SUPPORT_DEVICE_TYPE_CPU_16, OPENPGL_RADIANCE_CACHES,
// OPENPGL_IMAGE_SPACE_GUIDING_BUFFER, OPENPGL_DIRECTION_COMPRESSION and
// OPENPGL_RADIANCE_COMPRESSION stay undefined (upstream CMake defaults).
// Copyright 2024 Intel Corporation
// SPDX-License-Identifier: Apache-2.0

#pragma once
"""

PGL_VERSION = """\
// GENERATED by tools/vendor.py (upstream include/openpgl/version.h.in, %s).
// Copyright 2021 Intel Corporation
// SPDX-License-Identifier: Apache-2.0

#pragma once

#define OPENPGL_VERSION_MAJOR 0
#define OPENPGL_VERSION_MINOR 7
#define OPENPGL_VERSION_PATCH 1
#define OPENPGL_VERSION "0.7.1"
""" % PGL_PIN

# NOTE (ISA policy): upstream CMake builds the CPU_4 TU with -msse4.1 and the
# CPU_8 TU with -mavx2 etc.  The xiom link line cannot pass -m flags, and
# clang's per-function `target` attributes (the only no-flag lever) do NOT
# apply to lambda bodies -- always_inline intrinsics inside lambdas then fail
# ("always_inline function ... requires target feature ...", verified on the
# pinned clang).  The port therefore compiles the whole core at the x86-64
# SSE2 baseline and exposes ONLY the CPU_4 device (4-wide kernels; the device
# enum value 8 is declared for completeness but device_create rejects it).
# This is a documented declared-surface reduction (see SPEC.md section 1).
PGL_COMMON_DEFS = """\
#define OPENPGL_BUILD 1
#define BUILD_STATIC 1
#define OPENPGL_VERSION_MAJOR 0
#define OPENPGL_VERSION_MINOR 7
#define OPENPGL_VERSION_PATCH 1
#define OPENPGL_VERSION_STRING "0.7.1"
#define OPENPGL_DEVICE_TYPE_CPU_4 1
#define __TBB_NO_IMPLICIT_LINKAGE 1
#define __TBBMALLOC_NO_IMPLICIT_LINKAGE 1
"""

PGL_TUS = [
    # (wrapper stem, upstream source)
    ("pgl_tu_api", "api/api.cpp"),
    ("pgl_tu_device_cpu4", "api/deviceCPU4.cpp"),
    ("pgl_tu_isurface_sampling_distribution", "directional/ISurfaceSamplingDistribution.cpp"),
    ("pgl_tu_ivolume_sampling_distribution", "directional/IVolumeSamplingDistribution.cpp"),
    ("pgl_tu_vmm_phase_functions", "directional/vmm/VMMPhaseFunctions.cpp"),
]

EMBREE_TUS = [
    "common/simd/sse.cpp",
    "common/sys/alloc.cpp",
    "common/sys/barrier.cpp",
    "common/sys/condition.cpp",
    "common/sys/estring.cpp",
    "common/sys/mutex.cpp",
    "common/sys/sysinfo.cpp",
    "common/sys/thread.cpp",
]


def fail(msg):
    sys.stderr.write("vendor.py: ERROR: %s\n" % msg)
    sys.exit(1)


def copy_tree(src, dst):
    if not os.path.isdir(src):
        fail("missing source tree: %s" % src)
    if os.path.isdir(dst):
        shutil.rmtree(dst)
    shutil.copytree(src, dst)


def normalize_eol(root):
    # The pinned artifact is stored LF-only so re-carves hash identically on
    # any machine (a Windows git clone with core.autocrlf=true checks CRLF out;
    # the committed bytes must not depend on that). Binary files are untouched.
    changed = 0
    for base, _dirs, files in os.walk(root):
        for name in files:
            path = os.path.join(base, name)
            with open(path, "rb") as fh:
                data = fh.read()
            if b"\x00" in data or b"\r\n" not in data:
                continue
            with open(path, "wb") as fh:
                fh.write(data.replace(b"\r\n", b"\n"))
            changed += 1
    return changed


def iter_source_files(root):
    for base, _dirs, files in os.walk(root):
        for name in files:
            if name.lower().endswith((".h", ".hpp", ".cpp", ".in")):
                yield os.path.join(base, name)


def rewrite_includes(root, counts):
    embree_re = re.compile(r"#include <(embreeSrc/[^>]+)>")
    tbb_angle_re = re.compile(r"#include <(tbb/[^>]+)>")
    nano_re = re.compile(r"#include <nanoflann/include/nanoflann\.hpp>")

    for path in iter_source_files(root):
        with open(path, "r", encoding="utf-8", errors="surrogateescape", newline="") as fh:
            text = fh.read()
        out = text
        out, n1 = embree_re.subn(r'#include "third-party/\1"', out)
        out, n2 = tbb_angle_re.subn(r'#include "\1"', out)
        out, n4 = nano_re.subn(r'#include "third-party/nanoflann/include/nanoflann.hpp"', out)
        if out != text:
            with open(path, "w", encoding="utf-8", errors="surrogateescape", newline="") as fh:
                fh.write(out)
        counts["embree"] += n1
        counts["tbb"] += n2
        counts["nanoflann"] += n4


def replace_once(path, old, new):
    with open(path, "r", encoding="utf-8", newline="") as fh:
        text = fh.read()
    if text.count(old) != 1:
        fail("expected exactly one occurrence in %s, found %d" % (path, text.count(old)))
    with open(path, "w", encoding="utf-8", newline="") as fh:
        fh.write(text.replace(old, new))


def write_text(path, text):
    parent = os.path.dirname(path)
    if parent and not os.path.isdir(parent):
        os.makedirs(parent)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)


def tree_hash(root, exclude_names=("LICENSE", "LICENSE.txt")):
    # sha256 over sorted (relative path, file bytes) pairs; license texts are
    # excluded so the hash isolates the code artifact (jolt tree_hash shape).
    digest = hashlib.sha256()
    entries = []
    for base, _dirs, files in os.walk(root):
        for name in files:
            if name in exclude_names:
                continue
            full = os.path.join(base, name)
            rel = os.path.relpath(full, root).replace("\\", "/")
            entries.append((rel, full))
    for rel, full in sorted(entries):
        digest.update(rel.encode("utf-8"))
        digest.update(b"\x00")
        with open(full, "rb") as fh:
            digest.update(fh.read())
        digest.update(b"\x00")
    return digest.hexdigest()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--openpgl", required=True, help="openpgl clone root (E:\\repos\\openpgl)")
    parser.add_argument("--tbb", required=True, help="oneTBB clone root (E:\\repos\\oneTBB)")
    parser.add_argument("--out", default="", help="output vendor root (default packages/xiom-openpgl/vendor/openpgl)")
    parser.add_argument("--hash-only", action="store_true", help="only print the tree hash of --out")
    args = parser.parse_args()

    pkg_root = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
    out = os.path.abspath(args.out) if args.out else os.path.join(pkg_root, "vendor", "openpgl")

    if args.hash_only:
        print(tree_hash(out))
        return 0

    src_pgl = os.path.abspath(args.openpgl)
    src_tbb = os.path.abspath(args.tbb)

    # --- stage the upstream trees -------------------------------------------
    # Layout: EVERYTHING resolves through ONE include-chain root (this vendor
    # directory); the xiom link line has no -I passthrough.  Open PGL is
    # flattened at the root; oneTBB's include/oneapi -> oneapi/ and include/tbb
    # -> tbb/ keep their upstream `../oneapi/...` and `"oneapi/tbb/..."` forms
    # working through the chain; oneTBB/src/tbb rides under oneTBB/.
    copy_tree(os.path.join(src_pgl, "openpgl"), out)
    copy_tree(os.path.join(src_pgl, "third-party", "embreeSrc"),
              os.path.join(out, "third-party", "embreeSrc"))
    copy_tree(os.path.join(src_pgl, "third-party", "nanoflann"),
              os.path.join(out, "third-party", "nanoflann"))
    copy_tree(os.path.join(src_tbb, "include", "oneapi"), os.path.join(out, "oneapi"))
    copy_tree(os.path.join(src_tbb, "include", "tbb"), os.path.join(out, "tbb"))
    os.makedirs(os.path.join(out, "oneTBB"))
    copy_tree(os.path.join(src_tbb, "src", "tbb"), os.path.join(out, "oneTBB", "src", "tbb"))
    shutil.copy(os.path.join(src_pgl, "LICENSE.txt"), os.path.join(out, "LICENSE.txt"))
    for name in ("third-party-programs.txt", "third-party-programs-Embree.txt",
                 "third-party-programs-oneTBB.txt", "third-party-programs-ISPC.txt",
                 "third-party-programs-OIDN.txt"):
        src = os.path.join(src_pgl, name)
        if os.path.isfile(src):
            shutil.copy(src, os.path.join(out, name))
    shutil.copy(os.path.join(src_tbb, "LICENSE.txt"), os.path.join(out, "oneTBB", "LICENSE.txt"))

    # --- T0: LF normalization (deterministic pinned bytes) --------------------
    eol_changed = normalize_eol(out)

    # --- T1: include rewrite (openpgl + embreeSrc + nanoflann only) ----------
    counts = {"embree": 0, "tbb": 0, "nanoflann": 0}
    rewrite_includes(out, counts)
    if counts["tbb"] == 0 or counts["embree"] == 0:
        fail("include rewrite found no matches (embree=%d tbb=%d nanoflann=%d)" %
             (counts["embree"], counts["tbb"], counts["nanoflann"]))

    # --- T2: two portability gates (clang >= 20 target features) -------------
    replace_once(
        os.path.join(out, "oneapi", "tbb", "detail", "_config.h"),
        "#define __TBB_TSX_INTRINSICS_PRESENT (__RTM__ || __INTEL_COMPILER || (_MSC_VER>=1700 && (__TBB_x86_64 || __TBB_x86_32)))",
        "#define __TBB_TSX_INTRINSICS_PRESENT ((__RTM__ || __INTEL_COMPILER || (_MSC_VER>=1700 && (__TBB_x86_64 || __TBB_x86_32))) && !defined(__clang__))")
    replace_once(
        os.path.join(out, "oneTBB", "src", "tbb", "scheduler_common.h"),
        "#if __TBB_WAITPKG_INTRINSICS_PRESENT\n    if (governor::wait_package_enabled())",
        "#if __TBB_WAITPKG_INTRINSICS_PRESENT && !defined(__clang__)\n    if (governor::wait_package_enabled())")

    # --- generated headers ----------------------------------------------------
    write_text(os.path.join(out, "include", "openpgl", "defines.h"), PGL_DEFINES)
    write_text(os.path.join(out, "include", "openpgl", "version.h"), PGL_VERSION)

    # --- TU wrappers ----------------------------------------------------------
    for stem, source in PGL_TUS:
        body = ("%s\n// one openpgl library TU; upstream openpgl tree at pin v0.7.1\n"
                "// (%s); flattened at vendor/openpgl (quoted-include chain).\n"
                "%s#include \"%s\"\n"
                % (WRAPPER_HEADER, PGL_PIN, PGL_COMMON_DEFS, source))
        write_text(os.path.join(out, stem + ".cpp"), body)
    for source in EMBREE_TUS:
        base = os.path.splitext(os.path.basename(source))[0]
        write_text(os.path.join(out, "third-party", "embreeSrc", "embree_tu_%s.cpp" % base),
                   '%s\n// embreeSrc common TU (upstream openpgl third-party, pin v0.7.1).\n#include "%s"\n'
                   % (WRAPPER_HEADER, source))
    tbb_src_dir = os.path.join(out, "oneTBB", "src", "tbb")
    tbb_names = sorted(n for n in os.listdir(tbb_src_dir)
                       if n.endswith(".cpp") and os.path.isfile(os.path.join(tbb_src_dir, n)))
    for name in tbb_names:
        write_text(os.path.join(out, "tbb_tu_%s.cpp" % name[:-4]),
                   "%s\n// one oneTBB runtime TU; upstream oneTBB src/tbb at pin v2021.13.0\n"
                   "// (%s).\n#define __TBB_BUILD 1\n#define __TBB_DYNAMIC_LOAD_ENABLED 0\n"
                   "#define __TBB_SOURCE_DIRECTLY_INCLUDED 1\n#include \"oneTBB/src/tbb/%s\"\n"
                   % (WRAPPER_HEADER, TBB_PIN, name))

    counts_msg = ("include rewrites: embree=%d tbb=%d nanoflann=%d; eol-normalized=%d; "
                  "wrappers: pgl=%d embree=%d tbb=%d"
                  % (counts["embree"], counts["tbb"], counts["nanoflann"], eol_changed,
                     len(PGL_TUS), len(EMBREE_TUS), len(tbb_names)))

    # --- port.args.json (compile-order list for scripts/port.ps1) ------------
    vendor_rel = os.path.relpath(out, pkg_root).replace("\\", "/")
    entries = ["--cxx-standard", "17",
               "--c-source", "${PACKAGE_DIR}/src/pgl_bridge.cpp"]
    for stem, _src in PGL_TUS:
        entries += ["--c-source", "${PACKAGE_DIR}/%s/%s.cpp" % (vendor_rel, stem)]
    for source in EMBREE_TUS:
        base = os.path.splitext(os.path.basename(source))[0]
        entries += ["--c-source", "${PACKAGE_DIR}/%s/third-party/embreeSrc/embree_tu_%s.cpp"
                    % (vendor_rel, base)]
    for name in tbb_names:
        entries += ["--c-source", "${PACKAGE_DIR}/%s/tbb_tu_%s.cpp" % (vendor_rel, name[:-4])]
    entries += ["--timeout", "900"]
    port_args = "[\n" + ",\n".join('  "%s"' % e for e in entries) + "\n]\n"
    write_text(os.path.join(pkg_root, "port.args.json"), port_args)

    print("vendor.py: regenerated %s" % out)
    print("vendor.py: %s" % counts_msg)
    print("vendor.py: generated-tree sha256: %s" % tree_hash(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
