#!/usr/bin/env pwsh
# Generates keys_expected.h (driver key-fidelity table) from the package's
# transcribed Str constants in mediandk.xi.  The on-device driver compares
# each pair against the runtime symbol value (dlsym) -- the exhaustive
# proof that the constant cluster matches libmediandk.so.
# Fails (exit 1) unless exactly the declared 143 key constants are found.
$ErrorActionPreference = "Stop"
$here = $PSScriptRoot
$repo = Split-Path -Parent (Split-Path -Parent (Split-Path -Parent (Split-Path -Parent (Split-Path -Parent $here))))
$xi = Join-Path $repo "packages\xiom-mediandk\mediandk.xi"
$outFile = Join-Path $here "keys_expected.h"

$content = Get-Content -LiteralPath $xi -Raw
$re = [regex]'(?m)^pub const (AMEDIAFORMAT_KEY_[A-Z0-9_]+|AMEDIACODEC_KEY_[A-Z0-9_]+): Str = "([^"]*)";'
$pairs = @()
foreach ($m in $re.Matches($content)) {
    $pairs += [pscustomobject]@{ Symbol = $m.Groups[1].Value; Value = $m.Groups[2].Value }
}
if ($pairs.Count -ne 143) {
    Write-Host "gen-keys-expected: found $($pairs.Count) key constants, expected 143"
    exit 1
}
$dupes = @($pairs | Group-Object Symbol | Where-Object { $_.Count -gt 1 })
if ($dupes.Count -gt 0) {
    Write-Host "gen-keys-expected: duplicate symbols: $($dupes.Name -join ', ')"
    exit 1
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("/* Generated by gen-keys-expected.ps1 from packages/xiom-mediandk/mediandk.xi -- do not edit. */")
[void]$sb.AppendLine("#ifndef XM_KEYS_EXPECTED_H")
[void]$sb.AppendLine("#define XM_KEYS_EXPECTED_H")
[void]$sb.AppendLine("static const struct { const char* symbol; const char* value; } k_expected_keys[] = {")
foreach ($p in ($pairs | Sort-Object Symbol)) {
    [void]$sb.AppendLine("    { `"$($p.Symbol)`", `"$($p.Value)`" },")
}
[void]$sb.AppendLine("};")
[void]$sb.AppendLine("#define XM_EXPECTED_KEYS_COUNT $($pairs.Count)")
[void]$sb.AppendLine("#endif")
[System.IO.File]::WriteAllText($outFile, $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))
Write-Host "gen-keys-expected: $($pairs.Count) pairs -> $outFile"
exit 0
