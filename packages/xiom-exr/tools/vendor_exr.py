# SPDX-License-Identifier: MIT OR Apache-2.0
#
# Usage:  python tools/vendor_exr.py [--check]
#
# What it does:
#   1. verifies E:\repos\tinyexr knows the pinned commit (v3.2.0);
#   2. extracts every vendored file binary-safely with `git cat-file blob`
#      (the clone worktree is autocrlf-converted on Windows, so worktree
#      copies are NOT trustworthy);
#   3. applies ONE mechanical include rewrite to tinyexr.h --
#      `#include <miniz.h>` -> `#include "miniz.h"` -- so the single-TU
#      build resolves the vendored miniz through the quoted-include search
#      (the toolchain has no -I flag for --c-source files);
#   4. writes vendor/FILES.sha256 (upstream blob sha1 + raw sha256 +
#      vendored sha256 per file).
#
# --check re-extracts and compares without writing (drift guard).

import hashlib
import pathlib
import subprocess
import sys

PIN = "6f470c9ab24bf3992bc512ce07e8ecb00d9bf105"  # tag v3.2.0
CLONE = pathlib.Path("E:/repos/tinyexr")
ROOT = pathlib.Path(__file__).resolve().parent.parent
VENDOR = ROOT / "vendor" / "tinyexr"

# upstream path -> (vendored name, rewrite_include)
FILES = {
    "tinyexr.h": ("tinyexr.h", True),
    "exr_reader.hh": ("exr_reader.hh", False),
    "streamreader.hh": ("streamreader.hh", False),
    "deps/miniz/miniz.h": ("miniz.h", False),
    "deps/miniz/miniz.c": ("miniz.c", False),
    "LICENSE": ("LICENSE", False),
    "deps/miniz/LICENSE": ("LICENSE-miniz", False),
}


def git(*args: str) -> bytes:
    out = subprocess.run(
        ["git", "-C", str(CLONE), *args],
        capture_output=True, check=False,
    )
    if out.returncode != 0:
        raise RuntimeError(
            f"git {' '.join(args)} failed: {out.stderr.decode(errors='replace')}"
        )
    return out.stdout


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest().upper()


def main() -> int:
    check = "--check" in sys.argv
    head = git("rev-parse", f"{PIN}^{{commit}}").decode().strip()
    if head != PIN:
        raise RuntimeError(f"pin mismatch: {head} != {PIN}")

    rows = []
    for upstream_path, (name, rewrite) in FILES.items():
        raw = git("cat-file", "blob", f"{PIN}:{upstream_path}")
        blob_sha1 = git("rev-parse", f"{PIN}:{upstream_path}").decode().strip()
        data = raw
        if rewrite:
            needle = b"#include <miniz.h>"
            if data.count(needle) != 1:
                raise RuntimeError(
                    f"{upstream_path}: expected exactly one {needle!r}, "
                    f"found {data.count(needle)} -- upstream changed"
                )
            data = data.replace(needle, b'#include "miniz.h"')
        target = VENDOR / name
        if check:
            if not target.exists() or target.read_bytes() != data:
                raise RuntimeError(f"drift: {target} differs from the pin")
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
        rows.append((name, blob_sha1, sha256(raw), sha256(data), len(data)))

    manifest = [
        "# GENERATED by tools/vendor_exr.py -- do not edit by hand.",
        f"# upstream: github.com/syoyo/tinyexr @ {PIN} (tag v3.2.0)",
        "# columns: name  upstream_blob_sha1  upstream_raw_sha256  vendored_sha256  bytes",
        "# tinyexr.h carries one mechanical include rewrite (<miniz.h> -> \"miniz.h\").",
    ]
    for name, blob_sha1, raw_sha, vend_sha, size in rows:
        manifest.append(f"{name}  {blob_sha1}  {raw_sha}  {vend_sha}  {size}")
    if check:
        print("vendor_exr: %d file(s) verified at pin %s" % (len(rows), PIN))
    else:
        manifest_path = ROOT / "vendor" / "FILES.sha256"
        manifest_path.write_text("\n".join(manifest) + "\n", "utf-8")
        print("vendor_exr: %d file(s) written from pin %s" % (len(rows), PIN))
    for name, blob_sha1, raw_sha, vend_sha, size in rows:
        print(f"  {name:<16} blob={blob_sha1[:12]} raw={raw_sha[:12]} vend={vend_sha[:12]} {size}B")
    return 0


if __name__ == "__main__":
    sys.exit(main())
