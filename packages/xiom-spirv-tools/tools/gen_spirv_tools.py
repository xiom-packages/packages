def emit_constants(enums, consts, meta):
    lines = [HEADER_BLOCK]
    lines.append(BANNER.format(**meta))
    lines.append("")
    lines.append("module xiom.spirv_tools.constants")
    lines.append("")
    lines.append("// Source-generated enum values (header order preserved).")
    total = 0
    for ename, members in enums:
        lines.append("")
        lines.append("// ---- %s ----" % ename)
        for mname, mval in members:
            lines.append("pub const %s: Int = %d;" % (mname, mval))
            total += 1
    lines.append("")
    lines.append("// ---- file-scope constants ----")
    for cname, cval in consts:
        lines.append("pub const %s: Int = %d;" % (snake_to_scream(cname), cval))
        total += 1
    lines.append("")
    lines.append("/// Number of generated constant values (enum members + file constants).")
    lines.append("/// Complexity: O(1).")
    lines.append("pub fn st_constant_count() -> Int { return %d; }" % total)
    lines.append("")
    return "\n".join(lines), total


def snake_to_scream(name):
    s = re.sub(r"(?<!^)(?=[A-Z])", "_", name)
    return s.upper()


def emit_symbols(funcs, meta):
    lines = [HEADER_BLOCK]
    lines.append(BANNER.format(**meta))
    lines.append("")
    lines.append("module xiom.spirv_tools.symbols")
    lines.append("")
    lines.append("// Resolved symbol handles: one p_<c_name> field per declared C")
    lines.append("// function.  Zero means the shipped DLL does not export that name")
    lines.append("// (see st_resolve.xi and docs/COVERAGE.md).")
    lines.append("pub type StSymbols = {")
    for fn in funcs:
        lines.append("  p_%s: Int;" % snake(fn["name"]))
    lines.append("}")
    lines.append("")
    lines.append("/// Number of declared C functions (the oracle inventory).")
    lines.append("/// Complexity: O(1).")
    lines.append("pub fn st_declared_count() -> Int { return %d; }" % len(funcs))
    lines.append("")
    lines.append("/// Number of non-zero (resolved) handles in a symbol table.")
    lines.append("/// Complexity: O(1).")
    lines.append("pub fn st_resolved_count(syms: &StSymbols) -> Int {")
    lines.append("  var n = 0;")
    for fn in funcs:
        lines.append("  if syms.p_%s != 0 { n = n + 1; }" % snake(fn["name"]))
    lines.append("  return n;")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def emit_resolve(funcs, exported, missing, meta):
    lines = [HEADER_BLOCK]
    lines.append(BANNER.format(**meta))
    lines.append("")
    lines.append("module xiom.spirv_tools.resolve")
    lines.append("")
    lines.append("use xiom.ffi.dl;")
    lines.append("")
    lines.append("use xiom.spirv_tools.symbols;")
    lines.append("")
    lines.append("/// All dl-sym results for the declared C surface: the resolved")
    lines.append("/// handles plus the names the shipped DLL does not export.")
    lines.append("pub type StResolveOutcome = {")
    lines.append("  syms: StSymbols;")
    lines.append("  missing: Vec[Str];")
    lines.append("}")
    lines.append("")
    lines.append("/// Runtime probe results over the full declared name list.")
    lines.append("pub type StNameProbeReport = {")
    lines.append("  oracle_count: Int;")
    lines.append("  resolved_count: Int;")
    lines.append("  exported_missing: Vec[Str];")
    lines.append("  gap_resolved: Vec[Str];")
    lines.append("}")
    lines.append("")
    lines.append("/// Declared C function names, in header order.")
    lines.append("/// Complexity: O(1).")
    lines.append("pub fn st_oracle_names() -> Vec[Str] {")
    lines.append("  var v: Vec[Str] = Vec[Str].new();")
    for fn in funcs:
        lines.append('  v.push("%s");' % fn["name"])
    lines.append("  return v;")
    lines.append("}")
    lines.append("")
    lines.append("/// Declared names the shipped DLL exports (resolve proof set).")
    lines.append("/// Complexity: O(1).")
    lines.append("pub fn st_exported_names() -> Vec[Str] {")
    lines.append("  var v: Vec[Str] = Vec[Str].new();")
    for fn in funcs:
        if fn["name"] in exported:
            lines.append('  v.push("%s");' % fn["name"])
    lines.append("  return v;")
    lines.append("}")
    lines.append("")
    lines.append("/// Declared names NOT present in the shipped DLL's export table.")
    lines.append("/// Complexity: O(1).")
    lines.append("pub fn st_missing_names() -> Vec[Str] {")
    lines.append("  var v: Vec[Str] = Vec[Str].new();")
    for fn in funcs:
        if fn["name"] in missing:
            lines.append('  v.push("%s");' % fn["name"])
    lines.append("  return v;")
    lines.append("}")
    lines.append("")
    lines.append("/// Number of declared C functions (oracle N).")
    lines.append("/// Complexity: O(1).")
    lines.append("pub fn st_oracle_count() -> Int { return %d; }" % len(funcs))
    lines.append("")
    lines.append("/// Number of declared names exported by the shipped DLL.")
    lines.append("/// Complexity: O(1).")
    lines.append("pub fn st_exported_count() -> Int { return %d; }" % len(exported))
    lines.append("")
    lines.append("/// Resolve every declared name against a loaded library handle.")
    lines.append("/// Missing names land in `missing` with a zero handle.  Never Err:")
    lines.append("/// the shipped DLL is authoritative for what exists (B-20/G3 rule).")
    lines.append("/// Complexity: O(symbols).")
    lines.append("pub fn st_resolve_symbols(handle: Int) -> StResolveOutcome {")
    lines.append("  var missing: Vec[Str] = Vec[Str].new();")
    for i, fn in enumerate(funcs, 1):
        lines.append('  let r%d = dl.dl_sym(handle, "%s");' % (i, fn["name"]))
        lines.append(
            '  if !r%d.is_ok { missing.push("%s"); }' % (i, fn["name"])
        )
    lines.append("  return StResolveOutcome{")
    lines.append("    syms: StSymbols{")
    for i, fn in enumerate(funcs, 1):
        lines.append(
            "      p_%s: if r%d.is_ok { r%d.value } else { 0 };" % (snake(fn["name"]), i, i)
        )
    lines.append("    };")
    lines.append("    missing: missing")
    lines.append("  };")
    lines.append("}")
    lines.append("")
    lines.append("/// Resolve every declared name and classify the two deltas:")
    lines.append("/// names expected missing that resolved (DLL grew) and names")
    lines.append("/// expected present that did not (ABI mismatch).")
    lines.append("/// Complexity: O(symbols).")
    lines.append("pub fn st_probe_names(handle: Int) -> StNameProbeReport {")
    lines.append("  let names = st_oracle_names();")
    lines.append("  var resolved = 0;")
    lines.append("  var i = 0;")
    lines.append("  while i < names.len() {")
    lines.append("    let r = dl.dl_sym(handle, names[i]);")
    lines.append("    if r.is_ok { resolved = resolved + 1; }")
    lines.append("    i = i + 1;")
    lines.append("  }")
    lines.append('  let exported = st_exported_names();')
    lines.append("  var exported_missing: Vec[Str] = Vec[Str].new();")
    lines.append("  var j = 0;")
    lines.append("  while j < exported.len() {")
    lines.append("    let r2 = dl.dl_sym(handle, exported[j]);")
    lines.append("    if !r2.is_ok { exported_missing.push(exported[j]); }")
    lines.append("    j = j + 1;")
    lines.append("  }")
    lines.append("  let gap = st_missing_names();")
    lines.append("  var gap_resolved: Vec[Str] = Vec[Str].new();")
    lines.append("  var k = 0;")
    lines.append("  while k < gap.len() {")
    lines.append("    let r3 = dl.dl_sym(handle, gap[k]);")
    lines.append("    if r3.is_ok { gap_resolved.push(gap[k]); }")
    lines.append("    k = k + 1;")
    lines.append("  }")
    lines.append("  return StNameProbeReport{")
    lines.append("    oracle_count: names.len();")
    lines.append("    resolved_count: resolved;")
    lines.append("    exported_missing: exported_missing;")
    lines.append("    gap_resolved: gap_resolved")
    lines.append("  };")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def emit_wrappers(family_label, family_desc, funcs, meta):
    lines = [HEADER_BLOCK]
    lines.append(BANNER.format(**meta))
    lines.append("")
    lines.append("module xiom.spirv_tools.%s" % family_label)
    lines.append("")
    lines.append("use xiom.spirv_tools.symbols;")
    lines.append("")
    lines.append("// Typed wrappers: %s." % family_desc)
    lines.append("// Call convention: the fn-pointer cast and the call are confined to")
    lines.append("// the `unsafe` block (one per wrapper); the resolver owns dl_sym, so")
    lines.append("// nothing here touches the loader except through `syms`.")
    for fn in funcs:
        xfi = snake(fn["name"])
        decl_types, cast_types, arg_suffixes, rk, cast_ret = wrap_signature(fn)
        params_decl = ", ".join(
            "%s: %s" % (pname, xt) for (ctype, pname), xt in zip(fn["params"], decl_types)
        )
        args = ", ".join(
            pname + suffix for (ctype, pname), suffix in zip(fn["params"], arg_suffixes)
        )
        sig_params = ("syms: &StSymbols, " + params_decl) if params_decl else "syms: &StSymbols"
        cast_sig = "fn(%s)" % ", ".join(cast_types) if cast_types else "fn()"
        if cast_ret:
            cast_sig += " -> " + cast_ret
        c_sig = "%s %s(%s)" % (
            fn["ret"],
            fn["name"],
            ", ".join("%s %s" % (c, p) for c, p in fn["params"]) if fn["params"] else "void",
        )
        lines.append("")
        lines.append("/// C: %s" % c_sig)
        if rk == "void":
            lines.append("/// Complexity: O(1).")
            lines.append("pub fn st_%s(%s)" % (xfi, sig_params))
            lines.append("  requires: syms.p_%s != 0" % xfi)
            lines.append("{")
            lines.append("  unsafe {")
            lines.append("    let f_call = syms.p_%s as %s;" % (xfi, cast_sig))
            lines.append("    f_call(%s);" % args)
            lines.append("  }")
            lines.append("}")
        elif rk == "bool":
            lines.append("/// Complexity: O(1).")
            lines.append("pub fn st_%s(%s) -> Bool" % (xfi, sig_params))
            lines.append("  requires: syms.p_%s != 0" % xfi)
            lines.append("{")
            lines.append("  unsafe {")
            lines.append("    let f_call = syms.p_%s as %s;" % (xfi, cast_sig))
            lines.append("    return (f_call(%s) as Int) != 0;" % args)
            lines.append("  }")
            lines.append("}")
        elif rk == "cstr":
            lines.append('/// Returns "" when the C call yields NULL.')
            lines.append("/// Complexity: O(len).")
            lines.append("pub fn st_%s(%s) -> Str" % (xfi, sig_params))
            lines.append("  requires: syms.p_%s != 0" % xfi)
            lines.append("{")
            lines.append("  unsafe {")
            lines.append("    let f_call = syms.p_%s as %s;" % (xfi, cast_sig))
            lines.append("    let p = f_call(%s);" % args)
            lines.append("    if (p as Int) == 0 { return \"\"; }")
            lines.append("    return Str::from_c_str(p);")
            lines.append("  }")
            lines.append("}")
        elif rk == "void" or rk == "unit":
            pass
        else:
            lines.append("/// Complexity: O(1).")
            lines.append("pub fn st_%s(%s) -> Int" % (xfi, sig_params))
            lines.append("  requires: syms.p_%s != 0" % xfi)
            lines.append("{")
            lines.append("  unsafe {")
            lines.append("    let f_call = syms.p_%s as %s;" % (xfi, cast_sig))
            lines.append("    return f_call(%s) as Int;" % args)
            lines.append("  }")
            lines.append("}")
    lines.append("")
    return "\n".join(lines)


def generate(header_path, exports_path, out_dir, check_only):
    with open(header_path, "r", encoding="utf-8", errors="replace") as f:
        header_text = f.read()
    with open(header_path, "rb") as f:
        hdr_sha = hashlib.sha256(f.read()).hexdigest().upper()
    with open(exports_path, "r", encoding="utf-8") as f:
        exported = set(l.strip() for l in f if l.strip())

    meta = {
        "hdr": header_path,
        "hdr_sha": hdr_sha,
        "dll_sha": "see SPEC.md (pin)",
    }

    funcs = parse_functions(header_text)
    enums = parse_enums(header_text)
    consts = parse_module_constants(header_text)

    names = [f["name"] for f in funcs]
    if len(set(names)) != len(names):
        raise ValueError("duplicate function names in header parse")
    missing = [n for n in names if n not in exported]
    unknown_exports = sorted(n for n in exported if n not in set(names))

    files = {}
    files["st_constants.xi"], const_count = emit_constants(enums, consts, meta)
    files["st_symbols.xi"] = emit_symbols(funcs, meta)
    files["st_resolve.xi"] = emit_resolve(funcs, exported, missing, meta)
    for label, desc, fname in FAMILIES:
        fam = [f for f in funcs if family_of(f["name"]) == label]
        files[fname] = emit_wrappers(label, desc, fam, meta)

    print(
        "oracle=%d exported=%d missing=%d constants=%d enums=%d"
        % (len(funcs), len(exported), len(missing), const_count, len(enums))
    )
    if unknown_exports:
        print("export names not in the parsed C surface: %s" % ", ".join(unknown_exports))
    for label, desc, fname in FAMILIES:
        fam = [f for f in funcs if family_of(f["name"]) == label]
        print("  %-14s %2d  %s" % (label, len(fam), fname))

    drift = False
    for fname, content in sorted(files.items()):
        target = os.path.join(out_dir, fname)
        if check_only:
            existing = ""
            if os.path.exists(target):
                with open(target, "r", encoding="utf-8") as f:
                    existing = f.read()
            if existing != content:
                print("DRIFT: %s" % target)
                drift = True
        else:
            os.makedirs(out_dir, exist_ok=True)
            with open(target, "w", encoding="utf-8", newline="\n") as f:
                f.write(content)
            print("wrote %s (%d lines)" % (target, content.count("\n") + 1))
    if check_only and drift:
        return 1
    return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--header", default=DEFAULT_HEADER)
    ap.add_argument("--exports", default=DEFAULT_EXPORTS)
    ap.add_argument("--out", default=DEFAULT_OUT)
    ap.add_argument("--check", action="store_true", help="drift check; no writes")
    ap.add_argument(
        "--print-inventory",
        action="store_true",
        help="print the parsed oracle inventory (one function per line) and exit",
    )
    args = ap.parse_args()
    if args.print_inventory:
        with open(args.header, "r", encoding="utf-8", errors="replace") as f:
            text = f.read()
        with open(args.exports, "r", encoding="utf-8") as f:
            exported = set(l.strip() for l in f if l.strip())
        funcs = parse_functions(text)
        print("# oracle inventory: %s" % args.header)
        print("# %d declared spv* C functions; %d exported by the pinned DLL" % (len(funcs), len(exported)))
        for f in funcs:
            print(
                "%s\t%s\t%s"
                % (
                    f["name"],
                    family_of(f["name"]),
                    "exported" if f["name"] in exported else "NOT-EXPORTED",
                )
            )
        for ename, members in parse_enums(text):
            print("# enum %s: %d members" % (ename, len(members)))
        return 0
    return generate(args.header, args.exports, args.out, args.check)


if __name__ == "__main__":
    sys.exit(main())
