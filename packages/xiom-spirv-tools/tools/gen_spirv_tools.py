def strip_comments(text):
    """Remove // and /* */ comments (the header contains no string literals)."""
    out = []
    i = 0
    n = len(text)
    in_block = False
    while i < n:
        if in_block:
            if text.startswith("*/", i):
                in_block = False
                i += 2
            else:
                i += 1
        else:
            if text.startswith("/*", i):
                in_block = True
                i += 2
            elif text.startswith("//", i):
                j = text.find("\n", i)
                i = n if j < 0 else j
            else:
                out.append(text[i])
                i += 1
    return "".join(out)


def collapse(text):
    return re.sub(r"\s+", " ", text)


# --- Parsing -----------------------------------------------------------------

FUNC_RE = re.compile(
    r"(?:(?P<export>SPIRV_TOOLS_EXPORT)\s+)?"
    r"(?P<ret>[A-Za-z_][A-Za-z0-9_\s\*]*?)\s+"
    r"(?P<name>spv[A-Za-z0-9_]+)\s*\((?P<params>[^()]*)\)\s*;"
)
FPTR_TYPEDEF_RE = re.compile(r"typedef[^;]*?\(\s*\*\s*\w+\s*\)\s*\([^;]*\)\s*;")
ENUM_RE = re.compile(
    r"typedef\s+enum\s*(?P<tag>[A-Za-z_]\w*)?\s*\{(?P<body>[^}]*)\}\s*(?P<alias>[A-Za-z_]\w*)\s*;"
)


def parse_functions(text):
    """Return the ordered list of C function declarations."""
    t = collapse(strip_comments(text))
    t = FPTR_TYPEDEF_RE.sub(" ", t)
    funcs = []
    for m in FUNC_RE.finditer(t):
        ret = m.group("ret").strip()
        name = m.group("name")
        params_raw = m.group("params").strip()
        if "(" in ret:
            continue
        params = []
        if params_raw and params_raw != "void":
            for p in params_raw.split(","):
                p = p.strip()
                if not p:
                    continue
                # split trailing identifier from the C type
                mm = re.match(r"^(?P<ctype>.*?[\*\s])(?P<pname>[A-Za-z_]\w*)$", p)
                if mm:
                    ctype = mm.group("ctype").strip()
                    pname = mm.group("pname")
                else:
                    ctype = p
                    pname = "arg%d" % (len(params) + 1)
                params.append((ctype, pname))
        funcs.append(
            {
                "name": name,
                "ret": ret,
                "params": params,
                "exported": bool(m.group("export")),
            }
        )
    return funcs


def eval_enum_value(expr, index_hint):
    expr = expr.strip()
    if expr == "":
        return index_hint
    if expr.startswith("SPV_BIT("):
        inner = expr[len("SPV_BIT(") : -1].strip()
        return 1 << int(inner, 0)
    return int(expr, 0)


def parse_enums(text):
    """Return [(enum_name, [(member_name, value), ...]), ...]."""
    t = collapse(strip_comments(text))
    out = []
    for m in ENUM_RE.finditer(t):
        enum_name = m.group("alias")
        body = m.group("body")
        members = []
        next_value = 0
        for entry in body.split(","):
            entry = entry.strip()
            if not entry:
                continue
            name = None
            value = None
            fm = re.match(r"^SPV_FORCE_16_BIT_ENUM\(\s*(\w+)\s*\)$", entry)
            gm = re.match(r"^SPV_FORCE_32_BIT_ENUM\(\s*(\w+)\s*\)$", entry)
            if fm:
                name = "SPV_FORCE_16BIT_" + fm.group(1)
                value = 0x7FFF
            elif gm:
                name = "SPV_FORCE_32BIT_" + gm.group(1)
                value = 0x7FFFFFFF
            elif "=" in entry:
                left, right = entry.split("=", 1)
                name = left.strip()
                value = eval_enum_value(right, next_value)
            else:
                name = entry
                value = next_value
            if not re.match(r"^[A-Za-z_]\w*$", name):
                raise ValueError("bad enum member %r in %s" % (entry, enum_name))
            members.append((name, value))
            next_value = value + 1
        out.append((enum_name, members))
    return out


def parse_module_constants(text):
    """kDefaultMaxIdBound and friends (file-scope const static uint32_t)."""
    t = collapse(strip_comments(text))
    out = []
    for m in re.finditer(
        r"const\s+static\s+(?:uint32_t|unsigned int|int)\s+(\w+)\s*=\s*([^;]+);", t
    ):
        out.append((m.group(1), int(m.group(2).strip(), 0)))
    return out


# --- Type mapping (C -> XIOM) ------------------------------------------------

# Pointer parameters that receive an XIOM-owned out-slot (Vec[UInt8]); the C
# callee writes into it.  One owned slot per out-param (B-11 discipline).
OUT_SLOTS = {
    ("spvTextToBinary", "binary"),
    ("spvTextToBinary", "diagnostic"),
    ("spvTextToBinaryWithOptions", "binary"),
    ("spvTextToBinaryWithOptions", "diagnostic"),
    ("spvBinaryToText", "text"),
    ("spvBinaryToText", "diagnostic"),
    ("spvValidate", "diagnostic"),
    ("spvValidateWithOptions", "diagnostic"),
    ("spvValidateBinary", "diagnostic"),
    ("spvBinaryParse", "diagnostic"),
    ("spvOptimizerRun", "optimized_binary"),
    ("spvParseTargetEnv", "env"),
    ("spvParseVulkanEnv", "env"),
}

# Pointer parameters passed as *UInt8 (raw data in / struct views out).  The
# caller supplies either a Vec[UInt8] address or Str.c_str() (never pointer
# arithmetic -- B-17).
RAW_PTRS = {
    ("spvTextToBinary", "text"),
    ("spvTextToBinaryWithOptions", "text"),
    ("spvValidate", "binary"),
    ("spvValidateWithOptions", "binary"),
    ("spvDiagnosticCreate", "position"),
    ("spvDiagnosticCreate", "message"),
    ("spvParseTargetEnv", "s"),
    ("spvOptimizerRegisterPassFromFlag", "flag"),
}

# Pointer parameters fed from a COPIED-OUT foreign address (Int).  The
# Int->*UInt8 cast must happen inside the wrapper's confined block, on the
# call expression itself: a cast in a separate function does not survive on
# the v0.64.3 pin (probe evidence: helper-returned pointers sanitize to
# garbage -- the same int-to-ptr family as B-20).  Callers pass plain Int.
ADDR_PTRS = {
    ("spvBinaryToText", "binary"),
    ("spvValidateBinary", "words"),
    ("spvBinaryParse", "words"),
    ("spvOptimizerRun", "binary"),
    ("spvOptimizerRegisterPassesFromFlags", "flags"),
    ("spvOptimizerRegisterPassesFromFlagsWhilePreservingTheInterface", "flags"),
}

# Callback / user-data parameters stay Int so callers pass 0 (NULL) or a
# resolved address; function-pointer marshaling through cast calls is
# compiler-version sensitive (B-13 family), so 0 is the safe default.
FUNC_PTR_PARAMS = {
    ("spvBinaryParse", "user_data"),
    ("spvBinaryParse", "parse_header"),
    ("spvBinaryParse", "parse_instruction"),
    ("spvOptimizerSetMessageConsumer", "consumer"),
}


def snake(name):
    """spvContextCreate -> spv_context_create."""
    s = re.sub(r"(?<!^)(?=[A-Z])", "_", name)
    return s.lower()


def param_xiom(func, ctype, pname):
    """Return (xiom_type, arg_suffix) for one C parameter."""
    if (func, pname) in FUNC_PTR_PARAMS:
        return "Int", ""
    if (func, pname) in OUT_SLOTS or (func, pname) in RAW_PTRS:
        return "*UInt8", ""
    if (func, pname) in ADDR_PTRS:
        return "Int", " as *UInt8"
    if "*" in ctype:
        return "Int", ""
    return "Int", ""


def ret_kind(ctype):
    c = ctype.strip()
    if c == "void":
        return "void"
    if c == "bool":
        return "bool"
    if c == "spv_result_t":
        return "enum"
    if c.startswith("const char"):
        return "cstr"
    if c in ("uint32_t", "size_t"):
        return "uint"
    if c in ("int32_t", "int"):
        return "int"
    # Anything else is a pointer typedef (spv_context, spv_diagnostic,
    # spv_validator_options, spv_optimizer_t*, ...): 64-bit handle.
    return "ptr"


def wrap_signature(fn):
    """Return (decl_types, cast_types, arg_suffixes, ret_kind, cast_ret).

    decl_types  -- public XIOM parameter types.
    cast_types  -- ABI types in the fn-pointer cast (*UInt8 for every
                   pointer-shaped parameter, including ADDR_PTRS, whose
                   public type is Int and whose argument gets the inline
                   `as *UInt8` cast).
    """
    decl_types = []
    cast_types = []
    arg_suffixes = []
    for ctype, pname in fn["params"]:
        xt, suffix = param_xiom(fn["name"], ctype, pname)
        decl_types.append(xt)
        if xt == "*UInt8" or suffix == " as *UInt8":
            cast_types.append("*UInt8")
        else:
            cast_types.append("Int")
        arg_suffixes.append(suffix)
    rk = ret_kind(fn["ret"])
    cast_ret = {
        "void": None,
        "bool": "UInt8",
        "enum": "Int32",
        "cstr": "*UInt8",
        "ptr": "Int",
        "uint": "UInt32",
        "int": "Int32",
    }[rk]
    return decl_types, cast_types, arg_suffixes, rk, cast_ret


