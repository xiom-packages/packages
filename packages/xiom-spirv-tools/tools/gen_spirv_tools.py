#!/usr/bin/env python3
"""gen_spirv_tools.py -- XIOM binding generator for the SPIRV-Tools C API.

Part of the SDK-100 program (docs/checklists/vulkan-sdk-100.md, slice A1:
xiom.spirv-tools).  Parses the SPIRV-Tools public C header and emits XIOM
modules for the dynamic-loader binding, then cross-checks the C surface
against the shipped DLL's export table (committed evidence file).

What it parses (the oracle): every function declaration inside the header's
`extern "C"` block whose name starts with `spv`.  That is the C API surface
(`spv*`, documented as such by upstream).  The C++ API in libspirv.hpp
(`spvtools::Context`, `spvtools::Optimizer`, ...) is a separate, mangled
surface and is deliberately NOT bound here (see docs/COVERAGE.md split).

What it emits (all under --out, default `src/`):
  st_constants.xi       every enum value + kDefaultMaxIdBound as pub const
  st_symbols.xi         the StSymbols handle struct (p_<name> per function)
  st_resolve.xi         dl.dl_sym resolver + name tables + runtime probe
  st_core.xi            typed wrappers: version/target-env/context (7)
  st_validator.xi       typed wrappers: validator options (15)
  st_optimizer.xi       typed wrappers: optimizer + optimizer options (17)
  st_reducer_fuzzer.xi  typed wrappers: reducer/fuzzer options (13)
  st_codec.xi           typed wrappers: text/binary/validate/diag (13)
  st_operand.xi         typed wrappers: operand-type predicates (2)

Usage (from the package directory):
  python tools/gen_spirv_tools.py                 # regenerate src/*.xi
  python tools/gen_spirv_tools.py --check         # drift check (no writes)
  python tools/gen_spirv_tools.py --print-inventory

Generated files are deterministic: same header + same export dump => same
bytes.  Re-run after moving the SDK pin and commit the delta.
"""

