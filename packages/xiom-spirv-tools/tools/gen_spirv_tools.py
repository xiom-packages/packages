def family_of(name):
    if name.startswith("spvOperand"):
        return "operand"
    if name.startswith("spvValidatorOptions"):
        return "validator"
    if name.startswith("spvOptimizer"):
        return "optimizer"
    if name.startswith("spvReducerOptions") or name.startswith("spvFuzzerOptions"):
        return "reducer_fuzzer"
    if name.startswith(("spvSoftware", "spvTargetEnv", "spvParse", "spvContext")):
        return "core"
    return "codec"


