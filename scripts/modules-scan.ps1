# modules-scan.ps1 -- fleet check: packages must declare `modules:` in package.xi
# so registry-installed artifacts are importable (PULSE finding -1715 / fleet -1721-2).
# Report-only; retrofit happens at each package's next real touch (no version-less republish).
# With -WriteReport, regenerates docs/MODULES-COMPLIANCE.md.

param([switch]$WriteReport)

$ErrorActionPreference = "Stop"
$scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$root = Split-Path -Parent $scriptDir

$packages = Get-ChildItem (Join-Path $root "packages") -Directory |
    Where-Object { Test-Path (Join-Path $_.FullName "package.xi") } |
    Sort-Object Name

$declared = @()
$missing = @()

foreach ($p in $packages) {
    $mf = Join-Path $p.FullName "package.xi"
    $hit = Select-String -Path $mf -Pattern "modules\s*:" -List
    if ($hit) { $declared += $p.Name } else { $missing += $p.Name }
}

"modules-scan: $($packages.Count) package(s); declared=$($declared.Count); missing=$($missing.Count)"
if ($missing.Count -gt 0) { "MISSING modules: -- retrofit at next touch (fleet item REL-20261013-1721-bindings-2)" }

if ($WriteReport) {
    $out = Join-Path $root "docs/MODULES-COMPLIANCE.md"
    $ts = (Get-Date).ToUniversalTime().ToString("yyyy-MM-ddTHH:mm:ss'Z'")
    $lines = @()
    $lines += "<!-- GENERATED by scripts/modules-scan.ps1 -WriteReport; do not edit by hand. -->"
    $lines += "# Registry-consumability compliance: `modules:` declaration"
    $lines += ""
    $lines += "Generated: $ts"
    $lines += ""
    $lines += "Rule: every package declares ``modules: [...]`` in ``package.xi`` so the published"
    $lines += "artifact is importable from the registry (``use xiom.<pkg>;``). Retrofit at each"
    $lines += "package's next real touch; no version-less republish. Fleet item:"
    $lines += "REL-20261013-1721-bindings-2 (PULSE origin: -1715)."
    $lines += ""
    $lines += "| State | Count |"
    $lines += "|---|---|"
    $lines += "| Declared | $($declared.Count) |"
    $lines += "| Missing | $($missing.Count) |"
    $lines += "| Total | $($packages.Count) |"
    $lines += ""
    $lines += "## Missing ($($missing.Count))"
    $lines += ""
    $lines += ($missing -join ", ")
    $lines += ""
    Set-Content -Path $out -Value ($lines -join "`n") -Encoding UTF8
    "report written: docs/MODULES-COMPLIANCE.md"
}
