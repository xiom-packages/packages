# provenance-audit.ps1 -- owner protocol check: docs/UPSTREAM-FIRST.md
# Every package (new or pre-existing) states its provenance:
#   - ported/derived -> PROVENANCE.md with upstream + pinned commit/tag + license; or
#   - independent    -> PROVENANCE.md declaring it (no upstream).
# Retrofit happens at each package's next touch; new packages must land with it.
# Report-only for now (future: readiness advisory). Exit 0 always.

param([switch]$WriteReport)

$ErrorActionPreference = "Stop"
$scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$root = Split-Path -Parent $scriptDir

$packages = Get-ChildItem (Join-Path $root "packages") -Directory |
    Where-Object { Test-Path (Join-Path $_.FullName "package.xi") } |
    Sort-Object Name

$compliant = @()
$missing = @()
$incomplete = @()

foreach ($p in $packages) {
    $f = Join-Path $p.FullName "PROVENANCE.md"
    if (-not (Test-Path $f)) { $missing += $p.Name; continue }
    $c = Get-Content $f -Raw
    $declaresIndependent = $c -match "(?i)independent"
    $hasUpstream = $c -match "(?i)upstream"
    $hasPin = $c -match "(?i)(pinned|pin\s|commit\s|tag\s)"
    if ($declaresIndependent -or ($hasUpstream -and $hasPin)) {
        $compliant += $p.Name
    } else {
        $incomplete += $p.Name
    }
}

"provenance-audit: $($packages.Count) package(s); compliant=$($compliant.Count); missing=$($missing.Count); incomplete=$($incomplete.Count)"
if ($missing.Count -gt 0) { "MISSING PROVENANCE.md ($($missing.Count)) -- retrofit at next touch" }
if ($incomplete.Count -gt 0) { "INCOMPLETE ($($incomplete.Count)) -- add upstream+pin or an explicit independent declaration" }

if ($WriteReport) {
    $out = Join-Path $root "docs/PROVENANCE-COMPLIANCE.md"
    $ts = (Get-Date).ToUniversalTime().ToString("yyyy-MM-ddTHH:mm:ss'Z'")
    $lines = @()
    $lines += "<!-- GENERATED by scripts/provenance-audit.ps1 -WriteReport; do not edit by hand. -->"
    $lines += "# Provenance compliance (owner protocol: docs/UPSTREAM-FIRST.md)"
    $lines += ""
    $lines += "Generated: $ts"
    $lines += ""
    $lines += "Rule: every package states its provenance in ``PROVENANCE.md`` -- either"
    $lines += "upstream + pinned commit/tag + license (ported/derived), or an explicit"
    $lines += "independent declaration (original work, no upstream). Retrofit at each"
    $lines += "package's next touch; new packages must land with it. Bindings packages"
    $lines += "carry the same obligation (lane gates G6/G7)."
    $lines += ""
    $lines += "| State | Count |"
    $lines += "|---|---|"
    $lines += "| Compliant | $($compliant.Count) |"
    $lines += "| Missing PROVENANCE.md | $($missing.Count) |"
    $lines += "| Incomplete (no pin/independent) | $($incomplete.Count) |"
    $lines += "| Total | $($packages.Count) |"
    $lines += ""
    $lines += "## Compliant ($($compliant.Count))"
    $lines += ""
    $lines += ($compliant -join ", ")
    $lines += ""
    $lines += "## Retrofit backlog -- missing ($($missing.Count))"
    $lines += ""
    $lines += ($missing -join ", ")
    $lines += ""
    $lines += "## Retrofit backlog -- incomplete ($($incomplete.Count))"
    $lines += ""
    $lines += ($incomplete -join ", ")
    $lines += ""
    Set-Content -Path $out -Value ($lines -join "`n") -Encoding UTF8
    "report written: docs/PROVENANCE-COMPLIANCE.md"
}
